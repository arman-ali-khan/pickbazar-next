-- Drop existing tables with CASCADE to handle dependencies
DROP TABLE IF EXISTS public.order_items CASCADE;
DROP TABLE IF EXISTS public.orders CASCADE;
DROP TABLE IF EXISTS public.reviews CASCADE;
DROP TABLE IF EXISTS public.questions CASCADE;
DROP TABLE IF EXISTS public.wishlist_items CASCADE;
DROP TABLE IF EXISTS public.product_tags CASCADE;
DROP TABLE IF EXISTS public.products CASCADE;
DROP TABLE IF EXISTS public.tags CASCADE;
DROP TABLE IF EXISTS public.categories CASCADE;
DROP TABLE IF EXISTS public.cards CASCADE;
DROP TABLE IF EXISTS public.addresses CASCADE;
DROP TABLE IF EXISTS public.profiles CASCADE;

-- 1. Profiles Table
-- This table will store user profile data, extending the built-in auth.users table.
CREATE TABLE public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name text,
  avatar_url text,
  bio text,
  contact_number text,
  updated_at timestamp with time zone DEFAULT now()
);
COMMENT ON TABLE public.profiles IS 'User profile information.';

-- 2. Addresses Table
-- Stores shipping and billing addresses for users.
CREATE TABLE public.addresses (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  address_type text NOT NULL, -- 'billing' or 'shipping'
  title text,
  country text,
  city text,
  state text,
  zip text,
  street_address text,
  created_at timestamp with time zone DEFAULT now()
);
COMMENT ON TABLE public.addresses IS 'User addresses for billing and shipping.';

-- 3. Cards Table
-- Stores partial credit card information for users.
CREATE TABLE public.cards (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  card_type text,
  last4 text,
  expiry_month integer,
  expiry_year integer,
  created_at timestamp with time zone DEFAULT now()
);
COMMENT ON TABLE public.cards IS 'Saved payment card information.';

-- 4. Categories Table
-- Stores product categories, supporting a single level of sub-categories.
CREATE TABLE public.categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  slug text UNIQUE,
  description text,
  parent_id bigint REFERENCES public.categories(id) ON DELETE SET NULL,
  created_at timestamp with time zone DEFAULT now()
);
COMMENT ON TABLE public.categories IS 'Product categories and sub-categories.';

-- 5. Tags Table
-- Stores tags for products.
CREATE TABLE public.tags (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  slug text UNIQUE,
  created_at timestamp with time zone DEFAULT now()
);
COMMENT ON TABLE public.tags IS 'Product tags for filtering and searching.';

-- 6. Products Table
-- Stores all product information.
CREATE TABLE public.products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  slug text UNIQUE,
  description text,
  unit text,
  price numeric NOT NULL,
  original_price numeric,
  stock integer DEFAULT 0,
  status text DEFAULT 'draft'::text,
  category_id bigint REFERENCES public.categories(id) ON DELETE SET NULL,
  featured_image_url text,
  gallery_urls text[],
  created_at timestamp with time zone DEFAULT now()
);
COMMENT ON TABLE public.products IS 'All products available in the store.';

-- 7. Product Tags Junction Table
-- Links products and tags in a many-to-many relationship.
CREATE TABLE public.product_tags (
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  tag_id bigint NOT NULL REFERENCES public.tags(id) ON DELETE CASCADE,
  PRIMARY KEY (product_id, tag_id)
);
COMMENT ON TABLE public.product_tags IS 'Junction table for products and tags.';

-- 8. Reviews Table
-- Customer reviews for products.
CREATE TABLE public.reviews (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  rating integer NOT NULL CHECK (rating >= 1 AND rating <= 5),
  text text,
  status text DEFAULT 'Pending'::text, -- Pending, Approved, Hidden
  created_at timestamp with time zone DEFAULT now()
);
COMMENT ON TABLE public.reviews IS 'Customer reviews for products.';

-- 9. Questions Table
-- Customer questions about products.
CREATE TABLE public.questions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  question text NOT NULL,
  answer text,
  status text DEFAULT 'Pending'::text, -- Pending, Answered
  created_at timestamp with time zone DEFAULT now()
);
COMMENT ON TABLE public.questions IS 'Customer questions and answers about products.';

-- 10. Wishlist Items Table
-- Items a user has added to their wishlist.
CREATE TABLE public.wishlist_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  created_at timestamp with time zone DEFAULT now(),
  UNIQUE (user_id, product_id)
);
COMMENT ON TABLE public.wishlist_items IS 'User wishlist items.';

-- 11. Orders Table
-- Stores order information.
CREATE TABLE public.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  total numeric NOT NULL,
  status text NOT NULL,
  shipping_address_id bigint REFERENCES public.addresses(id) ON DELETE SET NULL,
  created_at timestamp with time zone DEFAULT now()
);
COMMENT ON TABLE public.orders IS 'Customer orders.';

-- 12. Order Items Table
-- Stores individual items within an order.
CREATE TABLE public.order_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  quantity integer NOT NULL,
  price numeric NOT NULL,
  created_at timestamp with time zone DEFAULT now()
);
COMMENT ON TABLE public.order_items IS 'Individual items within an order.';


-- Policies and Storage
-----------------------------------

-- Avatars Storage Bucket
INSERT INTO storage.buckets (id, name, public)
VALUES ('avatars', 'avatars', true)
ON CONFLICT (id) DO NOTHING;

CREATE POLICY "Avatar images are publicly accessible."
ON storage.objects FOR SELECT
USING (bucket_id = 'avatars');

CREATE POLICY "Anyone can upload an avatar."
ON storage.objects FOR INSERT
WITH CHECK (bucket_id = 'avatars');

CREATE POLICY "Anyone can update their own avatar."
ON storage.objects FOR UPDATE
USING (auth.uid() = owner)
WITH CHECK (bucket_id = 'avatars');

-- Products Storage Bucket
INSERT INTO storage.buckets (id, name, public)
VALUES ('products', 'products', true)
ON CONFLICT (id) DO NOTHING;

CREATE POLICY "Product images are publicly accessible."
ON storage.objects FOR SELECT
USING (bucket_id = 'products');

CREATE POLICY "Authenticated users can upload product images."
ON storage.objects FOR INSERT
TO authenticated
WITH CHECK (bucket_id = 'products');


