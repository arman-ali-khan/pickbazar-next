-- Drop existing policies, functions, and triggers to ensure a clean slate.
-- Dropping with CASCADE to handle dependencies automatically.

-- Drop policies on profiles table if they exist
drop policy if exists "Users can view their own profile" on public.profiles;
drop policy if exists "Users can update their own profile" on public.profiles;
drop policy if exists "Users can insert their own profile" on public.profiles;

-- Drop policies on addresses table if they exist
drop policy if exists "Users can view their own addresses" on public.addresses;
drop policy if exists "Users can insert their own addresses" on public.addresses;
drop policy if exists "Users can delete their own addresses" on public.addresses;

-- Drop policies on avatars storage if they exist
drop policy if exists "Avatar images are publicly accessible." on storage.objects;
drop policy if exists "Anyone can upload an avatar." on storage.objects;
drop policy if exists "Anyone can update their own avatar." on storage.objects;


-- Drop trigger and function for new user handling if they exist
drop trigger if exists on_auth_user_created on auth.users;
drop function if exists public.handle_new_user();

-- Drop tables with CASCADE to remove dependent objects like constraints.
drop table if exists public.addresses cascade;
drop table if exists public.profiles cascade;


--
-- Create profiles table
-- This table will store public-facing user data.
--
create table public.profiles (
  id uuid not null references auth.users on delete cascade,
  full_name text,
  avatar_url text,
  bio text,
  contact_number text,
  email text,

  primary key (id)
);

-- Comments for profiles table
comment on table public.profiles is 'Public user profiles, linked to auth.users.';

--
-- Create addresses table
--
create table public.addresses (
    id bigint generated by default as identity primary key,
    user_id uuid references public.profiles on delete cascade not null,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    address_type text,
    title text,
    country text,
    city text,
    state text,
    zip text,
    street_address text
);

-- Comments for addresses table
comment on table public.addresses is 'Stores user shipping and billing addresses.';


-- Set up Row Level Security (RLS)
--
-- Profiles
alter table public.profiles enable row level security;

create policy "Users can view their own profile" on public.profiles
  for select using (auth.uid() = id);

create policy "Users can insert their own profile" on public.profiles
  for insert with check (auth.uid() = id);

create policy "Users can update their own profile" on public.profiles
  for update using (auth.uid() = id) with check (auth.uid() = id);

-- Addresses
alter table public.addresses enable row level security;

create policy "Users can view their own addresses" on public.addresses
    for select using (auth.uid() = user_id);

create policy "Users can insert their own addresses" on public.addresses
    for insert with check (auth.uid() = user_id);

create policy "Users can delete their own addresses" on public.addresses
    for delete using (auth.uid() = user_id);


-- Function to create a profile for a new user
--
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, full_name, avatar_url, email)
  values (new.id, new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'avatar_url', new.email);
  return new;
end;
$$ language plpgsql security definer;

-- Trigger to run the function when a new user signs up
--
create or replace trigger on_auth_user_created
  after insert on auth.users for each row
  execute procedure public.handle_new_user();


-- Set up Storage for Avatars
--
insert into storage.buckets (id, name, public)
values ('avatars', 'avatars', true)
on conflict (id) do nothing;

create policy "Avatar images are publicly accessible." on storage.objects
  for select using ( bucket_id = 'avatars' );

create policy "Anyone can upload an avatar." on storage.objects
  for insert with check ( bucket_id = 'avatars' );
  
create policy "Anyone can update their own avatar." on storage.objects
    for update using (auth.uid() = owner) with check (bucket_id = 'avatars');
