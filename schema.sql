-- Drop table if it exists to ensure a clean slate
DROP TABLE IF EXISTS public.tags CASCADE;

-- Create the tags table
CREATE TABLE public.tags (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    slug text NOT NULL UNIQUE,
    created_at timestamp with time zone DEFAULT now()
);

-- Enable Row Level Security for the tags table
ALTER TABLE public.tags ENABLE ROW LEVEL SECURITY;

-- Drop existing policies to prevent conflicts
DROP POLICY IF EXISTS "Allow read access on tags" ON public.tags;
DROP POLICY IF EXISTS "Allow full management for authenticated users on tags" ON public.tags;

-- Create policies for the tags table
-- 1. Allow public read access to all tags.
CREATE POLICY "Allow read access on tags"
ON public.tags
FOR SELECT
USING (true);

-- 2. Allow authenticated users to insert, update, and delete tags.
CREATE POLICY "Allow full management for authenticated users on tags"
ON public.tags
FOR ALL -- This covers INSERT, UPDATE, DELETE
TO authenticated
USING (true)
WITH CHECK (true);

-- Notify PostgREST to reload the schema cache
-- This is crucial to make the new table and policies immediately available to the API
NOTIFY pgrst, 'reload schema';
