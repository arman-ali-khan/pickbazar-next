-- Create the tags table
CREATE TABLE IF NOT EXISTS public.tags (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    slug text NOT NULL UNIQUE,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);

-- Drop existing RLS policies to ensure a clean slate
DROP POLICY IF EXISTS "Public tags are viewable by everyone." ON public.tags;
DROP POLICY IF EXISTS "Authenticated users can manage tags" ON public.tags;

-- Enable Row Level Security
ALTER TABLE public.tags ENABLE ROW LEVEL SECURITY;

-- Create policy for public read access
CREATE POLICY "Public tags are viewable by everyone."
ON public.tags FOR SELECT
TO public
USING (true);

-- Create policy for authenticated users to manage tags
CREATE POLICY "Authenticated users can manage tags"
ON public.tags FOR ALL
TO authenticated
USING (true)
WITH CHECK (true);
