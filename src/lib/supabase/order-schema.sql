-- Drop existing types and functions to resolve ambiguity
DROP FUNCTION IF EXISTS public.create_order(numeric, jsonb, json, uuid);
DROP FUNCTION IF EXISTS public.create_order(numeric, jsonb, json);
DROP TYPE IF EXISTS public.order_item_input;

-- Create a table for orders
create table if not exists public.orders (
    id bigint generated by default as identity primary key,
    user_id uuid references auth.users not null,
    order_number text not null unique,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    total_amount numeric(10, 2) not null,
    status text not null,
    shipping_details jsonb
);

-- Create a table for order items
create table if not exists public.order_items (
    id bigint generated by default as identity primary key,
    order_id bigint references public.orders not null,
    product_id bigint references public.products not null,
    quantity integer not null,
    price numeric(10, 2) not null
);

-- Enable RLS for the tables
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- Create policies for RLS
create policy "Allow individual read access" on public.orders for select using (auth.uid() = user_id);
create policy "Allow individual read access" on public.order_items for select using (exists (
    select 1 from public.orders where orders.id = order_items.order_id and auth.uid() = orders.user_id
));

-- Allow admin full access
create policy "Allow admin full access" on public.orders for all using (true);
create policy "Allow admin full access" on public.order_items for all using (true);

-- Function to create an order and its items
create or replace function public.create_order(
    p_user_id uuid,
    p_total_amount numeric,
    p_shipping_details jsonb,
    p_items json
)
returns text
language plpgsql
security definer
as $$
declare
    v_order_id bigint;
    v_order_number text;
    item json;
begin
    -- Generate a unique order number
    v_order_number := 'ORD-' || to_char(now(), 'YYMMDD') || '-' || lpad( (nextval('orders_id_seq'))::text, 4, '0');

    -- Insert the order
    insert into public.orders (user_id, order_number, total_amount, shipping_details, status)
    values (p_user_id, v_order_number, p_total_amount, p_shipping_details, 'Pending')
    returning id into v_order_id;

    -- Insert order items
    for item in select * from json_array_elements(p_items)
    loop
        insert into public.order_items (order_id, product_id, quantity, price)
        values (
            v_order_id,
            (item->>'product_id')::bigint,
            (item->>'quantity')::integer,
            (item->>'price')::numeric
        );
    end loop;

    return v_order_number;
end;
$$;
