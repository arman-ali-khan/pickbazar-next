-- Drop all potential old versions of the function and related types with CASCADE
DROP FUNCTION IF EXISTS create_order(numeric,jsonb,order_item_input[]) CASCADE;
DROP FUNCTION IF EXISTS create_order(uuid,numeric,jsonb,order_item_input[]) CASCADE;
DROP FUNCTION IF EXISTS create_order(uuid,numeric,jsonb,json) CASCADE;
DROP FUNCTION IF EXISTS create_order(uuid,numeric,jsonb,jsonb) CASCADE;
DROP TYPE IF EXISTS order_item_input CASCADE;

-- Create the orders table with all necessary columns
create table if not exists
  orders (
    id bigint generated by default as identity primary key,
    user_id uuid references auth.users (id) on delete cascade,
    total_amount numeric not null,
    status text default 'Pending',
    shipping_details jsonb,
    order_number text unique,
    created_at timestamp with time zone default timezone ('utc'::text, now()) not null
  );

-- Create the order_items table
create table if not exists
  order_items (
    id bigint generated by default as identity primary key,
    order_id bigint references orders (id) on delete cascade,
    product_id bigint references products (id) on delete set null,
    quantity int not null,
    price numeric not null,
    created_at timestamp with time zone default timezone ('utc'::text, now()) not null
  );

-- Create the definitive function to create an order
create or replace function create_order (
  p_user_id uuid,
  p_total_amount numeric,
  p_shipping_details jsonb,
  p_items jsonb
) returns text as $$
declare
  new_order_id bigint;
  new_order_number text;
begin
  -- Generate a unique, human-readable order number
  new_order_number := 'ORD-' || to_char(now(), 'YYMMDD') || '-' || upper(substr(md5(random()::text), 1, 6));

  -- Insert the new order and get its ID
  insert into public.orders (user_id, total_amount, shipping_details, order_number, status)
  values (p_user_id, p_total_amount, p_shipping_details, new_order_number, 'Pending') returning id into new_order_id;

  -- Insert order items
  insert into public.order_items (order_id, product_id, quantity, price)
  select
    new_order_id,
    (item->>'product_id')::bigint,
    (item->>'quantity')::int,
    (item->>'price')::numeric
  from jsonb_array_elements(p_items) as item;

  return new_order_number;
end;
$$ language plpgsql volatile security definer;
