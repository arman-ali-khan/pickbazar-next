-- Drop dependent types and functions first in reverse order of creation
DROP TYPE IF EXISTS public.order_item_input CASCADE;

-- Create a custom type for order items, including price
CREATE TYPE public.order_item_input AS (
    product_id integer,
    quantity integer,
    price numeric
);

-- Drop old function signatures if they exist
DROP FUNCTION IF EXISTS public.create_order(uuid, numeric, jsonb, json);
DROP FUNCTION IF EXISTS public.create_order(numeric, jsonb, json, uuid);


-- Create or replace the function to insert an order and its items
CREATE OR REPLACE FUNCTION public.create_order(
    p_user_id uuid,
    p_total_amount numeric,
    p_shipping_details jsonb,
    p_items order_item_input[]
)
RETURNS text -- Returns the new order number
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    new_order_id integer;
    new_order_number text;
    item order_item_input;
BEGIN
    -- Generate a unique order number
    new_order_number := 'ORD-' || to_char(now(), 'YYMMDD') || '-' || lpad( (nextval('orders_id_seq'))::text, 4, '0');

    -- Insert the order
    INSERT INTO public.orders (user_id, total_amount, shipping_details, order_number, status)
    VALUES (p_user_id, p_total_amount, p_shipping_details, new_order_number, 'Pending')
    RETURNING id INTO new_order_id;

    -- Insert order items
    FOREACH item IN ARRAY p_items
    LOOP
        INSERT INTO public.order_items (order_id, product_id, quantity, price) -- Added price
        VALUES (new_order_id, item.product_id, item.quantity, item.price); -- Added item.price
    END LOOP;

    RETURN new_order_number;
END;
$$;


-- Create the orders table (ensure all columns from previous fixes are here)
CREATE TABLE IF NOT EXISTS public.orders (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id uuid REFERENCES auth.users(id),
    order_number text UNIQUE,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    status text DEFAULT 'Pending'::text NOT NULL,
    total_amount numeric NOT NULL,
    shipping_details jsonb,
    PRIMARY KEY (id)
);
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
GRANT ALL ON TABLE public.orders TO service_role, authenticated, anon;

-- Create the order_items table with the price column
CREATE TABLE IF NOT EXISTS public.order_items (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    order_id bigint REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id integer REFERENCES public.products(id),
    quantity integer NOT NULL,
    price numeric NOT NULL,
    PRIMARY KEY (id)
);
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;
GRANT ALL ON TABLE public.order_items TO service_role, authenticated, anon;


-- Grant usage on the sequence if not already done
DO $$
BEGIN
   IF NOT EXISTS (SELECT 1 FROM pg_sequences WHERE schemaname = 'public' AND sequencename = 'orders_id_seq') THEN
      CREATE SEQUENCE public.orders_id_seq;
   END IF;
END
$$;
GRANT USAGE, SELECT ON SEQUENCE public.orders_id_seq TO service_role, authenticated, anon;
