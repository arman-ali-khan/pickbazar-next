-- Create the definitive, robust create_order function
create or replace function public.create_order(
  p_user_id uuid,
  p_total_amount numeric,
  p_shipping_details jsonb,
  p_items jsonb
)
returns text
language plpgsql
security definer
as $$
declare
  new_order_id int;
  new_order_number text;
  item jsonb;
  item_product_id int;
  item_quantity int;
  item_price_at_purchase numeric;
begin
  -- Generate a unique order number
  new_order_number := 'ORD-' || substr(replace(gen_random_uuid()::text, '-', ''), 1, 8);

  -- Insert the order and get the new order's ID
  insert into public.orders (user_id, total_amount, shipping_details, order_number, status)
  values (p_user_id, p_total_amount, p_shipping_details, new_order_number, 'Pending')
  returning id into new_order_id;

  -- Insert order items by looping through the jsonb array (more robust)
  for item in select * from jsonb_array_elements(p_items)
  loop
    item_product_id := (item->>'product_id')::int;
    item_quantity := (item->>'quantity')::int;
    item_price_at_purchase := (item->>'price')::numeric;

    -- This check will raise an error if price is null, which is the problem we're seeing.
    if item_price_at_purchase is null then
      raise exception 'Price is null for product_id %', item_product_id;
    end if;

    insert into public.order_items (order_id, product_id, quantity, price_at_purchase)
    values (new_order_id, item_product_id, item_quantity, item_price_at_purchase);
  end loop;

  return new_order_number;
end;
$$;


-- Add Row-Level Security policies
-- Enable RLS on the tables
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- Drop existing policies to avoid conflicts before creating new ones
drop policy if exists "Users can view their own orders." on public.orders;
drop policy if exists "Users can view their own order items." on public.order_items;

-- Create new policies for users to view their own data
create policy "Users can view their own orders."
on public.orders for select
using (auth.uid() = user_id);

create policy "Users can view their own order items."
on public.order_items for select
using (exists (
  select 1 from orders
  where orders.id = order_items.order_id and orders.user_id = auth.uid()
));

