-- Drop old functions and types to ensure a clean slate
DROP FUNCTION IF EXISTS public.create_order(uuid, numeric, jsonb, jsonb);
DROP FUNCTION IF EXISTS public.create_order(uuid, numeric, jsonb, public.order_item_input[]);
DROP TYPE IF EXISTS public.order_item_input CASCADE;

-- Create orders table if it doesn't exist
CREATE TABLE IF NOT EXISTS public.orders (
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    order_number text UNIQUE,
    total_amount numeric NOT NULL,
    status text DEFAULT 'Pending'::text,
    shipping_details jsonb,
    created_at timestamp with time zone DEFAULT now(),
    CONSTRAINT orders_pkey PRIMARY KEY (id)
);

-- Create order_items table if it doesn't exist
CREATE TABLE IF NOT EXISTS public.order_items (
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    order_id integer REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id integer REFERENCES public.products(id) ON DELETE SET NULL,
    quantity integer NOT NULL,
    price_at_purchase numeric NOT NULL,
    CONSTRAINT order_items_pkey PRIMARY KEY (id)
);

-- Ensure necessary columns exist on existing tables, just in case.
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS order_number text;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS shipping_details jsonb;
ALTER TABLE public.order_items ADD COLUMN IF NOT EXISTS price_at_purchase numeric;
ALTER TABLE public.order_items ALTER COLUMN price_at_purchase SET NOT NULL;


-- New, robust create_order function using jsonb
CREATE OR REPLACE FUNCTION public.create_order(
    p_user_id uuid,
    p_total_amount numeric,
    p_shipping_details jsonb,
    p_items jsonb
)
RETURNS text AS $$
DECLARE
    new_order_id integer;
    new_order_number text;
    item jsonb;
BEGIN
    -- Generate a unique order number
    new_order_number := 'ORD-' || to_char(now(), 'YYYYMMDD') || '-' || substr(md5(random()::text), 1, 6);

    -- Insert the main order details
    INSERT INTO public.orders (user_id, total_amount, shipping_details, order_number, status, created_at)
    VALUES (p_user_id, p_total_amount, p_shipping_details, new_order_number, 'Pending', now())
    RETURNING id INTO new_order_id;

    -- Loop through the items from the jsonb array and insert them
    FOR item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        INSERT INTO public.order_items (order_id, product_id, quantity, price_at_purchase)
        VALUES (
            new_order_id,
            (item->>'product_id')::integer,
            (item->>'quantity')::integer,
            (item->>'price')::numeric
        );
    END LOOP;

    -- Return the new order number to the application
    RETURN new_order_number;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
