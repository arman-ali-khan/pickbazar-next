CREATE TYPE public.user_role AS ENUM ('customer', 'manager', 'admin', 'super-admin');

-- Step 3: Re-create the tables with the correct schema.
CREATE TABLE public.orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    order_number text NOT NULL UNIQUE DEFAULT 'ORD-' || substr(md5(random()::text), 0, 10),
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    total_amount numeric(10, 2) NOT NULL,
    status public.order_status DEFAULT 'Pending' NOT NULL,
    shipping_details jsonb NOT NULL,
    coupon_code text,
    discount_amount numeric(10, 2)
);

CREATE TABLE public.order_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id bigint NOT NULL REFERENCES public.products(id),
    quantity integer NOT NULL,
    price_at_purchase numeric(10, 2) NOT NULL
);

CREATE TABLE public.transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    amount numeric(10, 2) NOT NULL,
    payment_method text NOT NULL,
    status text DEFAULT 'Completed' NOT NULL, -- e.g., 'Completed', 'Failed'
    transaction_details jsonb
);

CREATE TABLE public.notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE,
    recipient_role user_role, -- e.g. for notifying all 'admin's
    title text NOT NULL,
    message text,
    link text,
    is_read boolean DEFAULT false NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    type notification_type
);

