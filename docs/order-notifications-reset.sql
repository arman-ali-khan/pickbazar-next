-- Step 5: Recreate the SINGLE, CORRECT 'create_order' function
CREATE OR REPLACE FUNCTION public.create_order(
    p_user_id uuid,
    p_total_amount numeric,
    p_shipping_details jsonb,
    p_items jsonb,
    p_payment_method text,
    p_transaction_details jsonb,
    p_coupon_code text,
    p_discount_amount numeric
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    new_order_id bigint;
    new_order_number text;
    new_transaction_id bigint;
    order_item jsonb;
BEGIN
    -- Generate a unique order number
    new_order_number := 'PB-' || to_char(now(), 'YYMMDD') || '-' || nextval('orders_id_seq');

    -- Insert the order
    INSERT INTO public.orders (user_id, total_amount, shipping_details, status, order_number, coupon_code, discount_amount)
    VALUES (p_user_id, p_total_amount, p_shipping_details, 'Pending', new_order_number, p_coupon_code, p_discount_amount)
    RETURNING id INTO new_order_id;

    -- Insert order items
    FOR order_item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        INSERT INTO public.order_items (order_id, product_id, quantity, price_at_purchase)
        VALUES (
            new_order_id,
            (order_item->>'product_id')::bigint,
            (order_item->>'quantity')::integer,
            (order_item->>'price')::numeric
        );
    END LOOP;

    -- Insert transaction
    INSERT INTO public.transactions (order_id, user_id, amount, payment_method, status, transaction_details)
    VALUES (new_order_id, p_user_id, p_total_amount, p_payment_method, 'Completed', p_transaction_details)
    RETURNING id into new_transaction_id;

    -- Create notification for admins
    INSERT INTO public.notifications (recipient_role, title, message, link, type)
    VALUES 
        ('admin'::public.user_role, 'New Order Received', 'A new order ' || new_order_number || ' has been placed.', '/admin/orders/' || new_order_number, 'new_order'),
        ('manager'::public.user_role, 'New Order Received', 'A new order ' || new_order_number || ' has been placed.', '/admin/orders/' || new_order_number, 'new_order');

    RETURN new_order_number;
END;
$$;


