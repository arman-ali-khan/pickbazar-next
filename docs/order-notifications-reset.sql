CREATE OR REPLACE FUNCTION public.get_admin_order_list()
RETURNS TABLE(
    id bigint,
    order_number text,
    created_at timestamp with time zone,
    total_amount numeric,
    status public.order_status,
    customer_name text,
    customer_email text,
    customer_avatar_url text
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT
        o.id,
        o.order_number,
        o.created_at,
        o.total_amount,
        o.status,
        COALESCE(p.full_name, (o.shipping_details->>'firstName' || ' ' || o.shipping_details->>'lastName'))::text AS customer_name,
        COALESCE(u.email, o.shipping_details->>'email')::text AS customer_email,
        p.avatar_url::text AS customer_avatar_url
    FROM
        public.orders o
    LEFT JOIN
        public.profiles p ON o.user_id = p.id
    LEFT JOIN
        auth.users u ON o.user_id = u.id
    ORDER BY
        o.created_at DESC;
$$;


CREATE OR REPLACE FUNCTION public.get_admin_transactions()
RETURNS TABLE(
    id bigint,
    order_id bigint,
    order_number text,
    customer_name text,
    customer_avatar text,
    amount numeric,
    payment_method text,
    status text,
    created_at timestamp with time zone
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT 
    t.id,
    t.order_id,
    o.order_number,
    COALESCE(p.full_name, (o.shipping_details->>'firstName' || ' ' || o.shipping_details->>'lastName'))::text as customer_name,
    p.avatar_url::text as customer_avatar,
    t.amount,
    t.payment_method,
    t.status,
    t.created_at
  FROM public.transactions t
  LEFT JOIN public.orders o ON t.order_id = o.id
  LEFT JOIN public.profiles p ON t.user_id = p.id
  ORDER BY t.created_at DESC;
$$;


CREATE OR REPLACE FUNCTION public.get_admin_notifications()
RETURNS TABLE(
    id bigint,
    title text,
    message text,
    link text,
    is_read boolean,
    created_at timestamp with time zone,
    type notification_type
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT id, title, message, link, is_read, created_at, type
  FROM public.notifications
  WHERE recipient_role IN ('admin', 'manager', 'super-admin')
  ORDER BY created_at DESC;
$$;

