-- Drop existing objects in reverse order of dependency to avoid errors
drop function if exists public.get_admin_order_list();
drop function if exists public.get_admin_notifications();
drop function if exists public.get_admin_order_details(text);
drop function if exists public.get_admin_transactions();
drop function if exists public.create_order(uuid, numeric, jsonb, jsonb[], text, jsonb, text, numeric);
drop trigger if exists on_order_created_notification on public.orders;
drop function if exists public.handle_new_order_notification();
drop table if exists public.notifications;
drop type if exists public.notification_type;
drop type if exists public.order_status;

-- Recreate types
create type public.order_status as enum ('Pending', 'Processing', 'Shipped', 'Delivered', 'Cancelled');
create type public.notification_type as enum ('new_order', 'new_review', 'status_update');

-- Recreate notifications table
create table public.notifications (
    id bigint generated by default as identity primary key,
    user_id uuid references auth.users(id) on delete cascade,
    recipient_role user_role, -- Assumes user_role type exists from previous migrations
    title text not null,
    message text,
    link text,
    is_read boolean default false,
    created_at timestamptz default now(),
    type notification_type
);
alter table public.notifications enable row level security;

-- Policies for notifications
create policy "Admins can see role-based notifications" on public.notifications for select to authenticated using (
  (get_my_role() = 'admin' and recipient_role = 'admin') or
  (get_my_role() = 'manager' and recipient_role = 'manager') or
  (get_my_role() = 'super-admin')
);
create policy "Users can see their own notifications" on public.notifications for select to authenticated using (auth.uid() = user_id);
create policy "Users can update their own notifications" on public.notifications for update to authenticated using (auth.uid() = user_id);

-- Recreate order notification trigger function
create or replace function public.handle_new_order_notification()
returns trigger
language plpgsql
security definer
as $$
begin
  insert into public.notifications (recipient_role, title, message, link, type)
  values ('admin', 'New Order Received', 'A new order #' || new.order_number || ' has been placed.', '/admin/orders/' || new.order_number, 'new_order');
  return new;
end;
$$;

-- Recreate trigger on orders table
create trigger on_order_created_notification
  after insert on public.orders
  for each row execute function public.handle_new_order_notification();


-- Recreate get_admin_notifications function
create or replace function public.get_admin_notifications()
returns table (
  id bigint,
  title text,
  message text,
  link text,
  is_read boolean,
  created_at timestamptz,
  type notification_type
)
language plpgsql
security definer
as $$
begin
  return query
  select n.id, n.title, n.message, n.link, n.is_read, n.created_at, n.type
  from public.notifications n
  where
    (n.recipient_role = 'admin' or n.recipient_role = 'manager' or n.recipient_role = 'super-admin')
    and (
      (get_my_role() = 'admin' and n.recipient_role = 'admin') or
      (get_my_role() = 'manager' and n.recipient_role = 'manager') or
      (get_my_role() = 'super-admin')
    )
  order by n.created_at desc
  limit 20;
end;
$$;


-- Recreate create_order function
create or replace function public.create_order(
    p_user_id uuid,
    p_total_amount numeric,
    p_shipping_details jsonb,
    p_items jsonb[],
    p_payment_method text,
    p_transaction_details jsonb,
    p_coupon_code text,
    p_discount_amount numeric
)
returns text
language plpgsql
as $$
declare
    new_order_id bigint;
    new_order_number text;
    new_transaction_id bigint;
    item jsonb;
begin
    -- Generate a unique order number
    new_order_number := 'PN-' || to_char(now(), 'YYMMDD') || '-' || (
      select lpad( (count(*)+1)::text, 4, '0') from orders where created_at::date = current_date
    );

    -- Insert into orders table
    insert into public.orders(user_id, total_amount, shipping_details, coupon_code, discount_amount, order_number, status)
    values (p_user_id, p_total_amount, p_shipping_details, p_coupon_code, p_discount_amount, new_order_number, 'Pending')
    returning id into new_order_id;

    -- Insert into order_items table
    foreach item in array p_items
    loop
        insert into public.order_items(order_id, product_id, quantity, price)
        values (new_order_id, (item->>'product_id')::bigint, (item->>'quantity')::int, (item->>'price')::numeric);
    end loop;
    
    -- Insert into transactions table
    insert into public.transactions(order_id, amount, payment_method, status, transaction_details)
    values(new_order_id, p_total_amount, p_payment_method, 'Completed', p_transaction_details)
    returning id into new_transaction_id;

    return new_order_number;
end;
$$;


-- Recreate get_admin_order_list function
create or replace function public.get_admin_order_list()
returns table (
    id bigint,
    order_number text,
    created_at timestamptz,
    total_amount numeric,
    status order_status,
    customer_name text,
    customer_email text,
    customer_avatar_url text
)
language sql
stable
security definer
as $$
  select
    o.id,
    o.order_number,
    o.created_at,
    o.total_amount,
    o.status,
    coalesce(p.full_name, (o.shipping_details ->> 'firstName') || ' ' || (o.shipping_details ->> 'lastName'))::text as customer_name,
    coalesce(auth_users.email, o.shipping_details ->> 'email')::text as customer_email,
    p.avatar_url::text as customer_avatar_url
  from
    public.orders as o
  left join
    public.profiles as p on o.user_id = p.id
  left join
    auth.users as auth_users on o.user_id = auth_users.id
  order by
    o.created_at desc;
$$;


-- Recreate get_admin_order_details function
create or replace function public.get_admin_order_details(p_order_number text)
returns table (
    id bigint,
    order_number text,
    created_at timestamptz,
    total_amount numeric,
    status order_status,
    shipping_details jsonb,
    coupon_code text,
    discount_amount numeric,
    payment_method text,
    transaction_details jsonb,
    profiles jsonb,
    order_items jsonb[]
)
language sql
stable
as $$
  select
    o.id,
    o.order_number,
    o.created_at,
    o.total_amount,
    o.status,
    o.shipping_details,
    o.coupon_code,
    o.discount_amount,
    t.payment_method,
    t.transaction_details,
    jsonb_build_object(
        'full_name', p.full_name,
        'avatar_url', p.avatar_url
    ) as profiles,
    array(
      select jsonb_build_object(
        'id', oi.id,
        'quantity', oi.quantity,
        'price_at_purchase', oi.price,
        'products', jsonb_build_object(
          'name', pr.name,
          'featured_image_url', pr.featured_image_url
        )
      )
      from public.order_items oi
      join public.products pr on oi.product_id = pr.id
      where oi.order_id = o.id
    ) as order_items
  from public.orders o
  left join public.profiles p on o.user_id = p.id
  left join public.transactions t on o.id = t.order_id
  where o.order_number = p_order_number;
$$;

-- Recreate get_admin_transactions
create or replace function public.get_admin_transactions()
returns table (
    id bigint,
    order_id bigint,
    order_number text,
    customer_name text,
    customer_avatar text,
    amount numeric,
    payment_method text,
    status text,
    created_at timestamptz
)
language sql
stable
as $$
  select
    t.id,
    t.order_id,
    o.order_number,
    coalesce(p.full_name, (o.shipping_details ->> 'firstName') || ' ' || (o.shipping_details ->> 'lastName')) as customer_name,
    p.avatar_url as customer_avatar,
    t.amount,
    t.payment_method,
    t.status,
    t.created_at
  from transactions t
  join orders o on t.order_id = o.id
  left join profiles p on o.user_id = p.id
  order by t.created_at desc;
$$;


