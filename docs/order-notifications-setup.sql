-- Comprehensive Reset Script for Orders, Transactions, and Notifications

-- Drop all related objects to ensure a clean slate.
-- Using CASCADE to ensure that any dependent objects are also dropped.
drop function if exists public.create_order cascade;
drop function if exists public.get_admin_notifications cascade;
drop function if exists public.get_admin_order_list cascade;
drop function if exists public.get_admin_transactions cascade;
drop table if exists public.notifications cascade;
drop table if exists public.orders cascade;
drop table if exists public.order_items cascade;
drop table if exists public.transactions cascade;
drop type if exists public.notification_type cascade;
drop type if exists public.order_status cascade;
drop type if exists public.transaction_status cascade;
drop sequence if exists public.order_number_seq;


-- 1. Recreate all ENUM types
create type public.order_status as enum ('Pending', 'Processing', 'Shipped', 'Delivered', 'Cancelled');
create type public.notification_type as enum ('new_order', 'order_shipped', 'new_review', 'refund_request', 'order_placed');
create type public.transaction_status as enum ('Pending', 'Completed', 'Failed');


-- 2. Recreate all tables
create table public.orders (
    id bigint generated by default as identity primary key,
    user_id uuid references public.profiles(id) on delete set null,
    total_amount numeric not null,
    shipping_details jsonb,
    status public.order_status default 'Pending' not null,
    created_at timestamp with time zone default now() not null,
    order_number text not null unique,
    coupon_code text,
    discount_amount numeric
);

create table public.order_items (
    id bigint generated by default as identity primary key,
    order_id bigint references public.orders(id) on delete cascade not null,
    product_id bigint references public.products(id) on delete set null,
    quantity int not null,
    price numeric not null -- This is the price_at_purchase
);

create table public.transactions (
    id bigint generated by default as identity primary key,
    order_id bigint references public.orders(id) on delete cascade not null,
    amount numeric not null,
    payment_method text not null,
    status public.transaction_status not null,
    transaction_details jsonb,
    created_at timestamp with time zone default now() not null
);

create table public.notifications (
    id bigint generated by default as identity primary key,
    user_id uuid references public.profiles(id) on delete cascade,
    title text not null,
    message text,
    link text,
    is_read boolean default false not null,
    created_at timestamp with time zone default now() not null,
    type public.notification_type
);


-- 3. Recreate sequence for order numbers
create sequence public.order_number_seq start 1;


-- 4. Recreate all database functions

-- Function: create_order
create or replace function public.create_order(
    p_user_id uuid,
    p_total_amount numeric,
    p_shipping_details jsonb,
    p_items jsonb,
    p_payment_method text,
    p_transaction_details jsonb,
    p_coupon_code text,
    p_discount_amount numeric
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
    new_order_id bigint;
    new_order_number text;
    item record;
begin
    -- Generate a unique order number
    new_order_number := 'PB-' || to_char(now(), 'YYMMDD') || '-' || nextval('order_number_seq');

    -- Insert the new order
    insert into public.orders (user_id, total_amount, shipping_details, status, order_number, coupon_code, discount_amount)
    values (p_user_id, p_total_amount, p_shipping_details, 'Pending', new_order_number, p_coupon_code, p_discount_amount)
    returning id into new_order_id;

    -- Insert order items
    for item in select * from jsonb_to_recordset(p_items) as x(product_id bigint, quantity int, price numeric)
    loop
        insert into public.order_items (order_id, product_id, quantity, price)
        values (new_order_id, item.product_id, item.quantity, item.price);
    end loop;

    -- Insert transaction record
    insert into public.transactions (order_id, amount, payment_method, status, transaction_details)
    values (new_order_id, p_total_amount, p_payment_method, 'Completed', p_transaction_details);
    
    -- Create notification for admins
    insert into public.notifications (user_id, title, message, link, type)
    select id, 'New Order Received', 'Order #' || new_order_number || ' has been placed.', '/admin/orders/' || new_order_number, 'new_order'
    from public.profiles where role in ('admin', 'super-admin');

    return new_order_number;
end;
$$;


-- Function: get_admin_order_list
create or replace function public.get_admin_order_list()
returns table(id bigint, order_number text, created_at timestamp with time zone, total_amount numeric, status public.order_status, customer_name text, customer_email text, customer_avatar_url text)
language sql
security definer
set search_path = public
as $$
    select
        o.id,
        o.order_number,
        o.created_at,
        o.total_amount,
        o.status,
        p.full_name as customer_name,
        u.email as customer_email,
        p.avatar_url as customer_avatar_url
    from
        public.orders o
        left join public.profiles p on o.user_id = p.id
        left join auth.users u on o.user_id = u.id
    order by
        o.created_at desc;
$$;


-- Function: get_admin_notifications
create or replace function public.get_admin_notifications()
returns table(id bigint, title text, message text, link text, is_read boolean, created_at timestamp with time zone, type public.notification_type)
language sql
security definer
set search_path = public
as $$
  select id, title, message, link, is_read, created_at, type
  from public.notifications
  where user_id in (select id from public.profiles where role in ('admin', 'super-admin'))
  order by created_at desc
  limit 20;
$$;


-- Function: get_admin_transactions
create or replace function public.get_admin_transactions()
returns table(id bigint, order_id bigint, order_number text, customer_name text, customer_avatar text, amount numeric, payment_method text, status public.transaction_status, created_at timestamp with time zone)
language sql
security definer
set search_path = public
as $$
    select
        t.id,
        t.order_id,
        o.order_number,
        p.full_name as customer_name,
        p.avatar_url as customer_avatar,
        t.amount,
        t.payment_method,
        t.status,  -- This now correctly refers to the transactions table status
        t.created_at
    from
        public.transactions t
        join public.orders o on t.order_id = o.id
        left join public.profiles p on o.user_id = p.id
    order by
        t.created_at desc;
$$;


-- 5. Re-enable Row Level Security and recreate policies
alter table public.orders enable row level security;

create policy "Allow authenticated users to see their own orders"
on public.orders for select
to authenticated
using (auth.uid() = user_id);

create policy "Allow authenticated users to create their own orders"
on public.orders for insert
to authenticated
with check (auth.uid() = user_id);

alter table public.order_items enable row level security;
create policy "Users can view their own order items"
on public.order_items for select
to authenticated
using (
  exists (
    select 1
    from orders
    where
      orders.id = order_items.order_id and orders.user_id = auth.uid()
  )
);

alter table public.transactions enable row level security;
create policy "Users can view their own transactions"
on public.transactions for select
to authenticated
using (
  exists (
    select 1
    from orders
    where
      orders.id = transactions.order_id and orders.user_id = auth.uid()
  )
);
