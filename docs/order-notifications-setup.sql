CREATE OR REPLACE FUNCTION public.create_notification(
    p_title text,
    p_message text,
    p_link text,
    p_user_id uuid,
    p_recipient_role public.user_role
) RETURNS void AS $$
DECLARE
    admin_profile RECORD;
BEGIN
    IF p_user_id IS NOT NULL THEN
        -- Insert notification for a specific user
        INSERT INTO public.notifications (user_id, title, message, link, type, recipient_role)
        VALUES (p_user_id, p_title, p_message, p_link, 'order_status_update', NULL);
    ELSIF p_recipient_role IS NOT NULL THEN
        -- Insert notification for all users with a specific role
        FOR admin_profile IN SELECT id FROM public.profiles WHERE role = p_recipient_role::text
        LOOP
            INSERT INTO public.notifications (user_id, title, message, link, type, recipient_role)
            VALUES (admin_profile.id, p_title, p_message, p_link, 'new_order', p_recipient_role);
        END LOOP;
    END IF;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION public.get_admin_notifications()
RETURNS TABLE(id bigint, title text, message text, link text, is_read boolean, created_at timestamp with time zone, type public.notification_type)
SECURITY DEFINER
AS $$
BEGIN
    RETURN QUERY
    SELECT n.id, n.title, n.message, n.link, n.is_read, n.created_at, n.type
    FROM public.notifications n
    JOIN public.profiles p ON n.user_id = p.id
    WHERE p.role IN ('admin', 'super-admin', 'manager')
    ORDER BY n.created_at DESC;
END;
$$ LANGUAGE plpgsql;

