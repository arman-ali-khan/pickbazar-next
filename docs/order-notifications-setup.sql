DROP POLICY IF EXISTS "Allow admin read access" ON public.notifications;


-- Policies for orders
CREATE POLICY "Allow individual user read access" ON public.orders FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Allow admin read access" ON public.orders FOR SELECT USING (public.is_admin_or_super_admin(auth.uid()));

-- Policies for order_items
CREATE POLICY "Allow user to read their own order items" ON public.order_items FOR SELECT USING (
  EXISTS (
    SELECT 1 FROM public.orders WHERE orders.id = order_items.order_id AND orders.user_id = auth.uid()
  )
);
CREATE POLICY "Allow admin read access" ON public.order_items FOR SELECT USING (public.is_admin_or_super_admin(auth.uid()));

-- Policies for transactions
CREATE POLICY "Allow user to read their own transactions" ON public.transactions FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Allow admin read access" ON public.transactions FOR SELECT USING (public.is_admin_or_super_admin(auth.uid()));

-- Policies for notifications
CREATE POLICY "Allow user to read their own notifications" ON public.notifications FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Allow admin read access" ON public.notifications FOR SELECT USING (
    recipient_role IN ('admin', 'super-admin') AND public.is_admin_or_super_admin(auth.uid())
);
