-- ========= COMPLETE DATABASE RESET FOR ORDERS AND NOTIFICATIONS =========
-- This script will drop all related tables, types, and functions and recreate them correctly.
-- Please run this entire script in your Supabase SQL Editor.

-- Step 1: Drop all existing related objects in reverse dependency order with CASCADE
-- This ensures a clean state regardless of previous errors.
DROP FUNCTION IF EXISTS public.create_order(uuid,numeric,jsonb,jsonb,text,jsonb,text,numeric) CASCADE;
DROP FUNCTION IF EXISTS public.get_admin_order_list() CASCADE;
DROP FUNCTION IF EXISTS public.get_admin_orders() CASCADE;
DROP TABLE IF EXISTS public.notifications CASCADE;
DROP TYPE IF EXISTS public.notification_type CASCADE;
DROP TYPE IF EXISTS public.transaction_status CASCADE;

-- Step 2: Re-create the ENUM types correctly
CREATE TYPE public.notification_type AS ENUM (
    'new_order',
    'order_shipped',
    'order_delivered',
    'new_review',
    'new_question',
    'new_refund_request',
    'order_placed'
);

CREATE TYPE public.transaction_status AS ENUM ('Pending', 'Completed', 'Failed');


-- Step 3: Re-create the notifications table
CREATE TABLE public.notifications (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id uuid NULL,
    title text NOT NULL,
    message text NULL,
    link text NULL,
    is_read boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    type notification_type NULL,
    CONSTRAINT notifications_pkey PRIMARY KEY (id),
    CONSTRAINT notifications_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users (id) ON UPDATE CASCADE ON DELETE CASCADE
);

-- Step 4: Re-apply Row Level Security (RLS) policies
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;
GRANT ALL ON TABLE public.notifications TO service_role;
CREATE POLICY "Users can see their own notifications" ON public.notifications FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Admins can see all notifications" ON public.notifications FOR SELECT USING (public.is_admin());


-- Step 5: Re-create the get_admin_order_list function
CREATE OR REPLACE FUNCTION public.get_admin_order_list()
RETURNS TABLE(
    id int,
    order_number text,
    created_at timestamptz,
    total_amount numeric,
    status order_status,
    customer_name text,
    customer_email text,
    customer_avatar_url text
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RETURN QUERY
    SELECT
        o.id,
        o.order_number,
        o.created_at,
        o.total_amount,
        o.status,
        p.full_name AS customer_name,
        u.email AS customer_email,
        p.avatar_url AS customer_avatar_url
    FROM
        public.orders o
    LEFT JOIN
        public.profiles p ON o.user_id = p.id
    LEFT JOIN
        auth.users u ON o.user_id = u.id
    ORDER BY
        o.created_at DESC;
END;
$$;


-- Step 6: Re-create the create_order function
CREATE OR REPLACE FUNCTION public.create_order(
    p_user_id uuid,
    p_total_amount numeric,
    p_shipping_details jsonb,
    p_items jsonb,
    p_payment_method text,
    p_transaction_details jsonb,
    p_coupon_code text,
    p_discount_amount numeric
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    new_order_id int;
    new_order_number text;
    item jsonb;
    new_transaction_id int;
BEGIN
    -- Insert into orders table and get the new order's ID and order_number
    INSERT INTO public.orders (user_id, total_amount, shipping_details, status, coupon_code, discount_amount)
    VALUES (p_user_id, p_total_amount, p_shipping_details, 'Pending'::order_status, p_coupon_code, p_discount_amount)
    RETURNING id, order_number INTO new_order_id, new_order_number;

    -- Insert into order_items table for each item in the cart
    FOR item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        INSERT INTO public.order_items (order_id, product_id, quantity, price_at_purchase)
        VALUES (new_order_id, (item->>'id')::int, (item->>'quantity')::int, (item->>'price')::numeric);
    END LOOP;

    -- Insert into transactions table
    INSERT INTO public.transactions(order_id, amount, payment_method, status, transaction_details, user_id)
    VALUES (new_order_id, p_total_amount, p_payment_method, 'Completed'::transaction_status, p_transaction_details, p_user_id)
    RETURNING id into new_transaction_id;

    -- Create notification for admin
    INSERT INTO public.notifications (user_id, title, message, link, type)
    SELECT
        p.id,
        'New Order Received',
        'A new order with number ' || new_order_number || ' has been placed.',
        '/admin/orders/' || new_order_number,
        'new_order'::notification_type
    FROM public.profiles p
    WHERE p.role IN ('admin', 'super-admin');
    
    -- Create notification for the customer
    INSERT INTO public.notifications (user_id, title, message, link, type)
    VALUES (
        p_user_id,
        'Order Placed Successfully',
        'Your order ' || new_order_number || ' has been confirmed.',
        '/profile/my-orders/' || new_order_number,
        'order_placed'::notification_type
    );

    RETURN new_order_number;
END;
$$;
