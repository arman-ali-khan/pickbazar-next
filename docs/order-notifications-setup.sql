
-- 1. Create custom types if they don't exist
-- Using DO...END to handle 'if not exists' for types
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'order_status') THEN
        CREATE TYPE order_status AS ENUM ('Pending', 'Processing', 'Shipped', 'Delivered', 'Cancelled');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'notification_type') THEN
        CREATE TYPE notification_type AS ENUM ('new_order', 'new_review', 'status_update');
    END IF;
END
$$;

-- 2. Create notifications table if it doesn't exist
CREATE TABLE IF NOT EXISTS notifications (
    id bigint generated by default as identity primary key,
    user_id uuid references auth.users(id),
    title text not null,
    message text,
    link text,
    is_read boolean default false,
    type notification_type,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);
-- RLS for notifications
ALTER TABLE notifications ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Admins can see all notifications" ON notifications;
CREATE POLICY "Admins can see all notifications" ON notifications FOR SELECT TO authenticated USING (is_admin(auth.uid()));
DROP POLICY IF EXISTS "Users can see their own notifications" ON notifications;
CREATE POLICY "Users can see their own notifications" ON notifications FOR SELECT TO authenticated USING (auth.uid() = user_id);
DROP POLICY IF EXISTS "Allow insert for service_role" on notifications;
CREATE POLICY "Allow insert for service_role" ON notifications FOR INSERT with check (true);


-- 3. Add transaction_details to transactions table if it doesn't exist
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS transaction_details jsonb;

-- 4. Create sequence for order numbers if it doesn't exist
CREATE SEQUENCE IF NOT EXISTS order_number_seq START 1001;

-- 5. Create or Replace the create_order function
CREATE OR REPLACE FUNCTION create_order(
  p_user_id uuid,
  p_total_amount numeric,
  p_shipping_details jsonb,
  p_items jsonb,
  p_payment_method text,
  p_transaction_details jsonb,
  p_coupon_code text DEFAULT NULL,
  p_discount_amount numeric DEFAULT 0
)
RETURNS text
LANGUAGE plpgsql
AS $$
DECLARE
  v_order_id int;
  v_order_number text;
  item record;
BEGIN
  -- Generate order number
  v_order_number := 'ORD-' || to_char(now(), 'YYMMDD') || '-' || nextval('order_number_seq');

  -- Create the order
  INSERT INTO orders(user_id, order_number, total_amount, status, shipping_details, coupon_code, discount_amount)
  VALUES (p_user_id, v_order_number, p_total_amount, 'Pending'::order_status, p_shipping_details, p_coupon_code, p_discount_amount)
  RETURNING id INTO v_order_id;

  -- Insert order items
  FOR item IN SELECT * FROM jsonb_to_recordset(p_items) AS x(product_id int, quantity int, price numeric)
  LOOP
    INSERT INTO order_items(order_id, product_id, quantity, price_at_purchase)
    VALUES (v_order_id, item.product_id, item.quantity, item.price);
  END LOOP;

  -- Create a transaction record
  INSERT INTO transactions(order_id, amount, payment_method, status, transaction_details)
  VALUES (v_order_id, p_total_amount, p_payment_method, 'Completed', p_transaction_details); -- Assuming payment is completed

  RETURN v_order_number;
END;
$$;

-- 6. Create or Replace the function to notify on new order
CREATE OR REPLACE FUNCTION handle_new_order_notification()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    INSERT INTO public.notifications (title, message, link, type)
    VALUES (
        'New Order Received!',
        'A new order with number ' || NEW.order_number || ' has been placed.',
        '/admin/orders/' || NEW.order_number,
        'new_order'
    );
    RETURN NEW;
END;
$$;

-- 7. Create the trigger for new order notifications, dropping if it exists
DROP TRIGGER IF EXISTS on_new_order ON orders;
CREATE TRIGGER on_new_order
AFTER INSERT ON orders
FOR EACH ROW
EXECUTE FUNCTION handle_new_order_notification();


-- 8. Create or replace the function to get admin order details, now including transaction info
CREATE OR REPLACE FUNCTION get_admin_order_details(p_order_number text)
RETURNS TABLE (
    id int,
    order_number text,
    created_at timestamp with time zone,
    total_amount numeric,
    status order_status,
    shipping_details jsonb,
    profiles jsonb,
    order_items jsonb,
    coupon_code text,
    discount_amount numeric,
    payment_method text,
    transaction_details jsonb
)
LANGUAGE sql
AS $$
    SELECT
        o.id,
        o.order_number,
        o.created_at,
        o.total_amount,
        o.status,
        o.shipping_details,
        jsonb_build_object(
            'full_name', p.full_name,
            'avatar_url', p.avatar_url
        ) as profiles,
        (
            SELECT jsonb_agg(
                jsonb_build_object(
                    'id', oi.id,
                    'quantity', oi.quantity,
                    'price_at_purchase', oi.price_at_purchase,
                    'products', jsonb_build_object(
                        'name', pr.name,
                        'featured_image_url', pr.featured_image_url
                    )
                )
            )
            FROM order_items oi
            JOIN products pr ON oi.product_id = pr.id
            WHERE oi.order_id = o.id
        ) as order_items,
        o.coupon_code,
        o.discount_amount,
        t.payment_method,
        t.transaction_details
    FROM orders o
    LEFT JOIN profiles p ON o.user_id = p.id
    LEFT JOIN transactions t ON o.id = t.order_id
    WHERE o.order_number = p_order_number;
$$;
