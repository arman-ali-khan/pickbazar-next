-- Complete Database Reset for Orders and Notifications

-- Start a transaction to ensure all commands succeed or fail together.
BEGIN;

-- Forcefully drop all related tables, types, and functions.
-- The CASCADE option will automatically remove any dependent objects (like functions).
DROP TABLE IF EXISTS public.notifications CASCADE;
DROP TABLE IF EXISTS public.order_items CASCADE;
DROP TABLE IF EXISTS public.transactions CASCADE;
DROP TABLE IF EXISTS public.orders CASCADE;

DROP TYPE IF EXISTS public.order_status CASCADE;
DROP TYPE IF EXISTS public.notification_type CASCADE;
DROP TYPE IF EXISTS public.transaction_status CASCADE;
DROP TYPE IF EXISTS public.payment_method CASCADE;

-- Re-create all types from a clean state.
CREATE TYPE public.order_status AS ENUM ('Pending', 'Processing', 'Shipped', 'Delivered', 'Cancelled');
CREATE TYPE public.notification_type AS ENUM ('new_order', 'new_review', 'order_shipped', 'order_placed', 'refund_request', 'status_change');
CREATE TYPE public.transaction_status AS ENUM ('Pending', 'Completed', 'Failed');
CREATE TYPE public.payment_method AS ENUM ('card', 'mobile-banking', 'sslcommerz', 'cod');


-- Re-create all tables.
CREATE TABLE public.orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES auth.users,
    order_number text UNIQUE NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    total_amount numeric(10, 2) NOT NULL,
    status public.order_status DEFAULT 'Pending'::public.order_status NOT NULL,
    shipping_details jsonb,
    coupon_code text,
    discount_amount numeric(10, 2)
);
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;


CREATE TABLE public.order_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint REFERENCES public.orders(id) ON DELETE CASCADE NOT NULL,
    product_id bigint REFERENCES public.products(id) ON DELETE SET NULL,
    quantity integer NOT NULL,
    price_at_purchase numeric(10, 2) NOT NULL
);
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;


CREATE TABLE public.transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint REFERENCES public.orders(id) ON DELETE CASCADE NOT NULL,
    user_id uuid REFERENCES auth.users NOT NULL,
    amount numeric(10, 2) NOT NULL,
    payment_method public.payment_method NOT NULL,
    status public.transaction_status DEFAULT 'Pending'::public.transaction_status NOT NULL,
    transaction_details jsonb,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;


CREATE TABLE public.notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES auth.users,
    title text NOT NULL,
    message text,
    link text,
    is_read boolean DEFAULT false NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    type public.notification_type
);
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;


-- Re-create all security policies.
CREATE POLICY "Allow users to see their own orders" ON public.orders FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Allow users to see their own order items" ON public.order_items FOR SELECT USING (exists(select 1 from orders where orders.id = order_items.order_id and auth.uid() = orders.user_id));
CREATE POLICY "Allow users to see their own transactions" ON public.transactions FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Allow admins to see all orders" ON public.orders FOR SELECT USING (public.is_admin());
CREATE POLICY "Allow admins to update orders" ON public.orders FOR UPDATE USING (public.is_admin());
CREATE POLICY "Allow admins to see all order items" ON public.order_items FOR SELECT USING (public.is_admin());
CREATE POLICY "Allow admins to see all transactions" ON public.transactions FOR SELECT USING (public.is_admin());
CREATE POLICY "Allow admins to manage notifications" ON public.notifications FOR ALL USING (public.is_admin());

-- A sequence for order numbers
CREATE SEQUENCE IF NOT EXISTS order_number_seq;


-- Re-create all functions correctly.
CREATE OR REPLACE FUNCTION public.create_order(
    p_user_id uuid,
    p_total_amount numeric,
    p_shipping_details jsonb,
    p_items jsonb,
    p_payment_method text,
    p_transaction_details jsonb,
    p_coupon_code text,
    p_discount_amount numeric
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  new_order_id bigint;
  new_order_number text;
  item record;
BEGIN
  -- Generate a unique order number
  new_order_number := 'PB-' || to_char(now(), 'YYMMDD') || '-' || (nextval('order_number_seq')::text);

  -- Create the order
  INSERT INTO public.orders(user_id, order_number, total_amount, shipping_details, coupon_code, discount_amount, status)
  VALUES (p_user_id, new_order_number, p_total_amount, p_shipping_details, p_coupon_code, p_discount_amount, 'Pending')
  RETURNING id INTO new_order_id;

  -- Insert order items
  FOR item IN SELECT * FROM jsonb_to_recordset(p_items) AS x(product_id int, quantity int, price numeric)
  LOOP
    INSERT INTO public.order_items(order_id, product_id, quantity, price_at_purchase)
    VALUES (new_order_id, item.product_id, item.quantity, item.price);
  END LOOP;

  -- Create a transaction record
  INSERT INTO public.transactions(order_id, user_id, amount, payment_method, status, transaction_details)
  VALUES (new_order_id, p_user_id, p_total_amount, p_payment_method::public.payment_method, 'Completed', p_transaction_details);

  -- Create a notification for the user
  INSERT INTO public.notifications(user_id, title, message, link, type)
  VALUES (p_user_id, 'Order Placed!', 'Your order ' || new_order_number || ' has been successfully placed.', '/profile/my-orders/' || new_order_number, 'order_placed');

  -- Create a notification for admins
  INSERT INTO public.notifications(user_id, title, message, link, type)
  SELECT id, 'New Order Received', 'A new order ' || new_order_number || ' has been placed.', '/admin/orders/' || new_order_number, 'new_order'
  FROM public.profiles WHERE role IN ('admin', 'super-admin');

  -- Return the order number
  RETURN new_order_number;
END;
$$;


CREATE OR REPLACE FUNCTION public.get_admin_notifications()
RETURNS TABLE (
    id bigint,
    title text,
    message text,
    link text,
    is_read boolean,
    created_at timestamp with time zone,
    type public.notification_type
)
LANGUAGE sql
SECURITY DEFINER
AS $$
  SELECT n.id, n.title, n.message, n.link, n.is_read, n.created_at, n.type
  FROM public.notifications n
  JOIN public.profiles p ON n.user_id = p.id
  WHERE p.role IN ('admin', 'super-admin')
  ORDER BY n.created_at DESC;
$$;


CREATE OR REPLACE FUNCTION public.get_admin_order_list()
RETURNS TABLE (
    id bigint,
    order_number text,
    created_at timestamp with time zone,
    total_amount numeric,
    status public.order_status,
    customer_name text,
    customer_email text,
    customer_avatar_url text
)
LANGUAGE sql
SECURITY DEFINER
AS $$
  SELECT
    o.id,
    o.order_number,
    o.created_at,
    o.total_amount,
    o.status,
    p.full_name AS customer_name,
    u.email AS customer_email,
    p.avatar_url AS customer_avatar_url
  FROM
    public.orders o
  LEFT JOIN
    public.profiles p ON o.user_id = p.id
  LEFT JOIN
    auth.users u ON o.user_id = u.id
  ORDER BY
    o.created_at DESC;
$$;


CREATE OR REPLACE FUNCTION public.get_admin_transactions()
RETURNS TABLE (
    id bigint,
    order_id bigint,
    order_number text,
    customer_name text,
    customer_avatar text,
    amount numeric,
    payment_method text,
    status public.transaction_status,
    created_at timestamp with time zone
)
LANGUAGE sql
SECURITY DEFINER
AS $$
  SELECT
    t.id,
    t.order_id,
    o.order_number,
    p.full_name as customer_name,
    p.avatar_url as customer_avatar,
    t.amount,
    t.payment_method::text,
    t.status,
    t.created_at
  FROM public.transactions t
  JOIN public.orders o ON t.order_id = o.id
  LEFT JOIN public.profiles p ON t.user_id = p.id
  ORDER BY t.created_at DESC;
$$;


