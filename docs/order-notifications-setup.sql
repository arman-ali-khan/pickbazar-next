CREATE OR REPLACE FUNCTION public.create_order(
    p_user_id uuid,
    p_total_amount numeric,
    p_shipping_details jsonb,
    p_items jsonb,
    p_payment_method text,
    p_transaction_details jsonb,
    p_coupon_code text,
    p_discount_amount numeric
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  new_order_id bigint;
  new_order_number text;
  item jsonb;
BEGIN
  -- Generate a unique order number
  new_order_number := 'ORD-' || to_char(now(), 'YYMMDDHH24MISS') || '-' || substr(md5(random()::text), 1, 6);

  -- Create the order
  INSERT INTO public.orders (user_id, total_amount, shipping_details, order_number, coupon_code, discount_amount)
  VALUES (p_user_id, p_total_amount, p_shipping_details, new_order_number, p_coupon_code, p_discount_amount)
  RETURNING id INTO new_order_id;
  
  -- Insert order items
  FOR item IN SELECT * FROM jsonb_array_elements(p_items)
  LOOP
    INSERT INTO public.order_items (order_id, product_id, quantity, price_at_purchase)
    VALUES (new_order_id, (item->>'product_id')::bigint, (item->>'quantity')::int, (item->>'price')::numeric);
  END LOOP;

  -- Create a transaction record
  INSERT INTO public.transactions (order_id, user_id, amount, payment_method, status, transaction_details)
  VALUES (new_order_id, p_user_id, p_total_amount, p_payment_method, 'Completed'::public.transaction_status, p_transaction_details);

  -- Create notification for admins
  PERFORM public.create_notification(
    'New Order Received',
    'A new order ' || new_order_number || ' has been placed.',
    '/admin/orders/' || new_order_number,
    NULL,
    'admin'::public.user_role
  );

  RETURN new_order_number;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_admin_order_list()
RETURNS TABLE(id bigint, order_number text, created_at timestamp with time zone, total_amount numeric, status public.order_status, customer_name text, customer_email text, customer_avatar_url text)
SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY
  SELECT
      o.id,
      o.order_number,
      o.created_at,
      o.total_amount,
      o.status,
      p.full_name as customer_name,
      u.email as customer_email,
      p.avatar_url as customer_avatar_url
  FROM
      public.orders o
  LEFT JOIN
      public.profiles p ON o.user_id = p.id
  LEFT JOIN
      auth.users u ON o.user_id = u.id
  ORDER BY o.created_at DESC;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION public.get_admin_order_details(p_order_number text)
RETURNS TABLE(
    id bigint, order_number text, created_at timestamp with time zone, total_amount numeric, status public.order_status, shipping_details jsonb, profiles json, order_items json, coupon_code text, discount_amount numeric, payment_method text, transaction_details jsonb
)
SECURITY DEFINER
AS $$
BEGIN
    RETURN QUERY
    SELECT
        o.id,
        o.order_number,
        o.created_at,
        o.total_amount,
        o.status,
        o.shipping_details,
        (SELECT row_to_json(p.*) FROM public.profiles p WHERE p.id = o.user_id) as profiles,
        (SELECT json_agg(json_build_object(
            'id', oi.id,
            'quantity', oi.quantity,
            'price_at_purchase', oi.price_at_purchase,
            'products', (SELECT row_to_json(prod.*) FROM public.products prod WHERE prod.id = oi.product_id)
        )) FROM public.order_items oi WHERE oi.order_id = o.id) as order_items,
        o.coupon_code,
        o.discount_amount,
        t.payment_method,
        t.transaction_details
    FROM
        public.orders o
    LEFT JOIN
        public.transactions t ON o.id = t.order_id
    WHERE
        o.order_number = p_order_number;
END;
$$ LANGUAGE plpgsql;

