DROP TYPE IF EXISTS public.notification_type CASCADE;
DROP TYPE IF EXISTS public.user_role CASCADE;


-- Create custom types
CREATE TYPE public.order_status AS ENUM ('Pending', 'Processing', 'Shipped', 'Delivered', 'Cancelled');
CREATE TYPE public.notification_type AS ENUM ('new_order', 'new_review', 'status_update');
CREATE TYPE public.user_role AS ENUM ('admin', 'manager', 'super-admin');


-- Create tables
CREATE TABLE public.orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    order_number text UNIQUE NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    total_amount numeric(10, 2) NOT NULL,
    status order_status NOT NULL DEFAULT 'Pending',
    shipping_details jsonb NOT NULL,
    payment_method text,
    coupon_code text,
    discount_amount numeric(10, 2)
);
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.order_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
    quantity integer NOT NULL,
    price_at_purchase numeric(10, 2) NOT NULL
);
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    amount numeric(10, 2) NOT NULL,
    payment_method text NOT NULL,
    transaction_details jsonb,
    status text NOT NULL DEFAULT 'Completed' -- e.g., Completed, Failed
);
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE,
    recipient_role user_role, -- For admin notifications
    title text NOT NULL,
    message text,
    link text,
    is_read boolean NOT NULL DEFAULT false,
    type notification_type,
    created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

-- Create RLS policies
CREATE POLICY "Allow authenticated users to read their own orders" ON public.orders FOR SELECT TO authenticated USING (auth.uid() = user_id);
CREATE POLICY "Allow authenticated users to insert their own orders" ON public.orders FOR INSERT TO authenticated WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Allow admin users to access all orders" ON public.orders FOR ALL TO service_role USING (true);

CREATE POLICY "Allow users to read their own order items" ON public.order_items FOR SELECT TO authenticated USING ((SELECT user_id FROM public.orders WHERE id = order_id) = auth.uid());
CREATE POLICY "Allow admin users to access all order items" ON public.order_items FOR ALL TO service_role USING (true);

CREATE POLICY "Allow users to read their own transactions" ON public.transactions FOR SELECT TO authenticated USING ((SELECT user_id FROM public.orders WHERE id = order_id) = auth.uid());
CREATE POLICY "Allow admin users to access all transactions" ON public.transactions FOR ALL TO service_role USING (true);

CREATE POLICY "Allow users to read their own notifications" ON public.notifications FOR SELECT TO authenticated USING (auth.uid() = user_id);
CREATE POLICY "Allow admin users to read admin notifications" ON public.notifications FOR SELECT TO authenticated USING (get_my_role() = recipient_role::text);
CREATE POLICY "Allow admin users to update their notifications" ON public.notifications FOR UPDATE TO authenticated USING (get_my_role() = recipient_role::text);
CREATE POLICY "Allow admin users to do anything" ON public.notifications FOR ALL TO service_role USING (true);

-- Create functions
CREATE OR REPLACE FUNCTION public.create_order(
    p_user_id uuid,
    p_total_amount numeric,
    p_shipping_details jsonb,
    p_items jsonb[],
    p_payment_method text,
    p_transaction_details jsonb,
    p_coupon_code text,
    p_discount_amount numeric
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    new_order_id bigint;
    new_order_number text;
    item jsonb;
BEGIN
    -- Generate a unique order number
    new_order_number := 'ORD-' || to_char(now(), 'YYMMDD') || '-' || nextval('orders_id_seq');

    -- Insert the new order and get its ID
    INSERT INTO public.orders (user_id, total_amount, shipping_details, order_number, payment_method, coupon_code, discount_amount)
    VALUES (p_user_id, p_total_amount, p_shipping_details, new_order_number, p_payment_method, p_coupon_code, p_discount_amount)
    RETURNING id INTO new_order_id;

    -- Insert order items
    FOREACH item IN ARRAY p_items
    LOOP
        INSERT INTO public.order_items (order_id, product_id, quantity, price_at_purchase)
        VALUES (
            new_order_id,
            (item->>'product_id')::bigint,
            (item->>'quantity')::integer,
            (item->>'price')::numeric
        );
    END LOOP;

    -- Insert transaction record
    INSERT INTO public.transactions (order_id, amount, payment_method, transaction_details)
    VALUES (new_order_id, p_total_amount, p_payment_method, p_transaction_details);

    -- Insert a notification for admins
    INSERT INTO public.notifications (recipient_role, title, message, link, type)
    VALUES ('admin', 'New Order Received', 'A new order ' || new_order_number || ' has been placed.', '/admin/orders/' || new_order_number, 'new_order');

    -- Return the order number
    RETURN new_order_number;
END;
$$;


CREATE OR REPLACE FUNCTION public.get_admin_order_list()
RETURNS TABLE(
    id bigint,
    order_number text,
    created_at timestamptz,
    total_amount numeric,
    status order_status,
    customer_name text,
    customer_email text,
    customer_avatar_url text
)
LANGUAGE sql
SECURITY DEFINER
AS $$
    SELECT
        o.id,
        o.order_number,
        o.created_at,
        o.total_amount,
        o.status,
        COALESCE(p.full_name, (o.shipping_details->>'firstName') || ' ' || (o.shipping_details->>'lastName')) AS customer_name,
        COALESCE(u.email, (o.shipping_details->>'email')) AS customer_email,
        p.avatar_url AS customer_avatar_url
    FROM
        public.orders o
    LEFT JOIN
        auth.users u ON o.user_id = u.id
    LEFT JOIN
        public.profiles p ON o.user_id = p.id
    ORDER BY
        o.created_at DESC;
$$;


CREATE OR REPLACE FUNCTION public.get_admin_order_details(p_order_number text)
RETURNS TABLE(
    id bigint,
    order_number text,
    created_at timestamptz,
    total_amount numeric,
    status order_status,
    shipping_details jsonb,
    profiles jsonb,
    order_items jsonb,
    coupon_code text,
    discount_amount numeric,
    payment_method text,
    transaction_details jsonb
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RETURN QUERY
    SELECT
        o.id,
        o.order_number,
        o.created_at,
        o.total_amount,
        o.status,
        o.shipping_details,
        jsonb_build_object(
            'full_name', p.full_name,
            'avatar_url', p.avatar_url
        ) as profiles,
        (SELECT jsonb_agg(jsonb_build_object(
            'id', oi.id,
            'quantity', oi.quantity,
            'price_at_purchase', oi.price_at_purchase,
            'products', jsonb_build_object(
                'name', prod.name,
                'featured_image_url', prod.featured_image_url
            )
        )) FROM public.order_items oi JOIN public.products prod ON oi.product_id = prod.id WHERE oi.order_id = o.id) as order_items,
        o.coupon_code,
        o.discount_amount,
        t.payment_method,
        t.transaction_details
    FROM
        public.orders o
    LEFT JOIN
        public.profiles p ON o.user_id = p.id
    LEFT JOIN
        public.transactions t ON o.id = t.order_id
    WHERE
        o.order_number = p_order_number;
END;
$$;


CREATE OR REPLACE FUNCTION public.get_admin_notifications()
RETURNS TABLE (
    id bigint,
    title text,
    message text,
    link text,
    is_read boolean,
    created_at timestamptz,
    type notification_type
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RETURN QUERY
    SELECT n.id, n.title, n.message, n.link, n.is_read, n.created_at, n.type
    FROM public.notifications n
    WHERE n.recipient_role = 'admin'::public.user_role
    ORDER BY n.created_at DESC
    LIMIT 20;
END;
$$;
