-- Re-create functions
-- Function to get the role of the current user
CREATE OR REPLACE FUNCTION public.get_my_role()
RETURNS text
LANGUAGE sql
SECURITY DEFINER
AS $$
  select role from public.profiles where id = auth.uid();
$$;


-- Function to get admin notifications
CREATE OR REPLACE FUNCTION public.get_admin_notifications()
RETURNS TABLE(id int, title text, message text, link text, is_read boolean, created_at timestamptz, type public.notification_type)
LANGUAGE sql
SECURITY DEFINER
AS $$
  SELECT id, title, message, link, is_read, created_at, type
  FROM public.notifications
  WHERE user_id IS NULL -- Admin notifications have null user_id
  ORDER BY created_at DESC;
$$;


-- Function to get admin order list
CREATE OR REPLACE FUNCTION public.get_admin_order_list()
RETURNS TABLE(id int, order_number text, created_at timestamptz, total_amount numeric, status public.order_status, customer_name text, customer_email text, customer_avatar_url text)
LANGUAGE sql
STABLE
SECURITY DEFINER
AS $$
  SELECT
    o.id,
    o.order_number,
    o.created_at,
    o.total_amount,
    o.status,
    p.full_name as customer_name,
    u.email as customer_email,
    p.avatar_url as customer_avatar_url
  FROM
    public.orders o
  LEFT JOIN
    public.profiles p ON o.user_id = p.id
  LEFT JOIN
    auth.users u ON o.user_id = u.id
  ORDER BY
    o.created_at DESC;
$$;


-- Function to create an order
CREATE OR REPLACE FUNCTION public.create_order(
    p_user_id uuid,
    p_total_amount numeric,
    p_shipping_details jsonb,
    p_items jsonb,
    p_payment_method text,
    p_transaction_details jsonb,
    p_coupon_code text,
    p_discount_amount numeric
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  new_order_id bigint;
  new_order_number text;
  item jsonb;
BEGIN
  -- Insert the order and get the new ID and order number
  INSERT INTO public.orders (user_id, total_amount, shipping_details, status, coupon_code, discount_amount)
  VALUES (p_user_id, p_total_amount, p_shipping_details, 'Pending', p_coupon_code, p_discount_amount)
  RETURNING id, order_number INTO new_order_id, new_order_number;

  -- Insert order items
  FOR item IN SELECT * FROM jsonb_array_elements(p_items)
  LOOP
    INSERT INTO public.order_items (order_id, product_id, quantity, price_at_purchase)
    VALUES (new_order_id, (item->>'product_id')::bigint, (item->>'quantity')::int, (item->>'price')::numeric);
  END LOOP;

  -- Insert transaction
  INSERT INTO public.transactions (order_id, user_id, amount, payment_method, status, transaction_details)
  VALUES (new_order_id, p_user_id, p_total_amount, p_payment_method, 'Completed', p_transaction_details);

  -- Create a notification for admins
  INSERT INTO public.notifications (title, message, link, type)
  VALUES ('New Order Placed', 'A new order ' || new_order_number || ' has been placed.', '/admin/orders/' || new_order_number, 'new_order');

  -- Create a notification for the user
  INSERT INTO public.notifications (user_id, title, message, link, type)
  VALUES (p_user_id, 'Order Placed!', 'Your order ' || new_order_number || ' has been successfully placed.', '/profile/my-orders/' || new_order_number, 'order_placed');

  RETURN new_order_number;
END;
$$;

