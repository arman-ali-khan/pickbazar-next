-- 1. Create ENUM types
CREATE TYPE public.order_status AS ENUM ('Pending', 'Processing', 'Shipped', 'Delivered', 'Cancelled');
CREATE TYPE public.notification_type AS ENUM ('new_order', 'new_review', 'order_placed', 'order_shipped');
CREATE TYPE public.transaction_status AS ENUM ('Pending', 'Completed', 'Failed');

-- 2. Create tables

-- Orders Table
CREATE TABLE public.orders (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    order_number text UNIQUE NOT NULL,
    total_amount numeric(10, 2) NOT NULL,
    status public.order_status DEFAULT 'Pending',
    shipping_details jsonb,
    coupon_code text,
    discount_amount numeric(10, 2),
    created_at timestamp with time zone DEFAULT now()
);
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

-- Order Items Table
CREATE TABLE public.order_items (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    order_id bigint REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id bigint REFERENCES public.products(id) ON DELETE SET NULL,
    quantity integer NOT NULL,
    price_at_purchase numeric(10, 2) NOT NULL
);
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;

-- Transactions Table
CREATE TABLE public.transactions (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    order_id bigint REFERENCES public.orders(id) ON DELETE CASCADE NOT NULL,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    amount numeric(10, 2) NOT NULL,
    payment_method text,
    transaction_details jsonb,
    status public.transaction_status DEFAULT 'Completed',
    created_at timestamp with time zone DEFAULT now()
);
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;

-- Refunds Table
CREATE TABLE public.refunds (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    order_id bigint REFERENCES public.orders(id) ON DELETE CASCADE NOT NULL,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    amount numeric(10, 2) NOT NULL,
    reason text NOT NULL,
    status text DEFAULT 'Pending',
    created_at timestamp with time zone DEFAULT now(),
    updated_at timestamp with time zone DEFAULT now()
);
ALTER TABLE public.refunds ENABLE ROW LEVEL SECURITY;

-- Notifications Table
CREATE TABLE public.notifications (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE,
    type public.notification_type NOT NULL,
    title text NOT NULL,
    message text,
    link text,
    is_read boolean DEFAULT false,
    created_at timestamp with time zone DEFAULT now()
);
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

-- 3. Create Functions

-- Function to create an order
CREATE OR REPLACE FUNCTION public.create_order(
    p_user_id uuid,
    p_total_amount numeric,
    p_shipping_details jsonb,
    p_items jsonb,
    p_payment_method text,
    p_transaction_details jsonb,
    p_coupon_code text,
    p_discount_amount numeric
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_order_id bigint;
    v_order_number text;
    item jsonb;
BEGIN
    -- Generate a unique order number
    v_order_number := 'ORD-' || to_char(now(), 'YYYYMMDD') || '-' || substr(md5(random()::text), 0, 7);

    -- Insert into orders table
    INSERT INTO public.orders (user_id, order_number, total_amount, shipping_details, coupon_code, discount_amount, status)
    VALUES (p_user_id, v_order_number, p_total_amount, p_shipping_details, p_coupon_code, p_discount_amount, 'Pending')
    RETURNING id INTO v_order_id;

    -- Insert into order_items table
    FOR item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        INSERT INTO public.order_items (order_id, product_id, quantity, price_at_purchase)
        VALUES (v_order_id, (item->>'product_id')::bigint, (item->>'quantity')::int, (item->>'price')::numeric);
    END LOOP;

    -- Insert into transactions table
    INSERT INTO public.transactions (order_id, user_id, amount, payment_method, transaction_details, status)
    VALUES (v_order_id, p_user_id, p_total_amount, p_payment_method, p_transaction_details, 'Completed');
    
    -- Create notification for new order (for admins)
    INSERT INTO public.notifications (user_id, type, title, message, link)
    SELECT
        p.id,
        'new_order'::public.notification_type,
        'New Order Received',
        'A new order ' || v_order_number || ' has been placed.',
        '/admin/orders/' || v_order_number
    FROM public.profiles p
    WHERE p.role IN ('admin', 'manager', 'super-admin');

    -- Create notification for the customer
    INSERT INTO public.notifications (user_id, type, title, message, link)
    VALUES (
        p_user_id,
        'order_placed'::public.notification_type,
        'Order Placed Successfully!',
        'Your order ' || v_order_number || ' has been placed.',
        '/profile/my-orders/' || v_order_number
    );

    RETURN v_order_number;
END;
$$;


-- Function to get admin notifications
CREATE OR REPLACE FUNCTION public.get_admin_notifications()
RETURNS TABLE (
    id bigint,
    title text,
    message text,
    link text,
    is_read boolean,
    created_at timestamptz,
    type public.notification_type
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT 
        n.id,
        n.title,
        n.message,
        n.link,
        n.is_read,
        n.created_at,
        n.type
    FROM public.notifications n
    JOIN public.profiles p ON n.user_id = p.id
    WHERE p.role IN ('admin', 'manager', 'super-admin')
    ORDER BY n.created_at DESC;
END;
$$;

-- Function to get admin order details
CREATE OR REPLACE FUNCTION public.get_admin_order_details(p_order_number text)
RETURNS TABLE (
    id bigint,
    order_number text,
    created_at timestamptz,
    total_amount numeric,
    status public.order_status,
    shipping_details jsonb,
    profiles jsonb,
    order_items jsonb,
    coupon_code text,
    discount_amount numeric,
    payment_method text,
    transaction_details jsonb
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT 
        o.id,
        o.order_number,
        o.created_at,
        o.total_amount,
        o.status,
        o.shipping_details,
        jsonb_build_object('full_name', p.full_name, 'avatar_url', p.avatar_url),
        (SELECT jsonb_agg(jsonb_build_object(
            'id', oi.id,
            'quantity', oi.quantity,
            'price_at_purchase', oi.price_at_purchase,
            'products', (SELECT jsonb_build_object('name', pr.name, 'featured_image_url', pr.featured_image_url) FROM public.products pr WHERE pr.id = oi.product_id)
        )) FROM public.order_items oi WHERE oi.order_id = o.id),
        o.coupon_code,
        o.discount_amount,
        (SELECT t.payment_method FROM public.transactions t WHERE t.order_id = o.id LIMIT 1),
        (SELECT t.transaction_details FROM public.transactions t WHERE t.order_id = o.id LIMIT 1)
    FROM public.orders o
    LEFT JOIN public.profiles p ON o.user_id = p.id
    WHERE o.order_number = p_order_number;
END;
$$;

-- Function to get admin refunds
CREATE OR REPLACE FUNCTION public.get_admin_refunds()
RETURNS TABLE (
    id bigint,
    order_id bigint,
    order_number text,
    amount numeric,
    status text,
    reason text,
    created_at timestamptz,
    user_id uuid,
    customer_name text,
    customer_avatar_url text
)
LANGUAGE plpgsql
AS $$
BEGIN
  RETURN QUERY
  SELECT
    r.id,
    r.order_id,
    o.order_number,
    r.amount,
    r.status,
    r.reason,
    r.created_at,
    r.user_id,
    p.full_name as customer_name,
    p.avatar_url as customer_avatar_url
  FROM public.refunds r
  JOIN public.orders o ON r.order_id = o.id
  JOIN public.profiles p ON r.user_id = p.id
  ORDER BY r.created_at DESC;
END;
$$;

-- Function to get admin transactions
CREATE OR REPLACE FUNCTION public.get_admin_transactions()
RETURNS TABLE(
    id int,
    order_id int,
    order_number text,
    customer_name text,
    customer_avatar text,
    amount numeric,
    payment_method text,
    status public.transaction_status,
    created_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RETURN QUERY
    SELECT 
        t.id::int,
        t.order_id::int,
        o.order_number,
        p.full_name,
        p.avatar_url,
        t.amount,
        t.payment_method,
        t.status,
        t.created_at
    FROM public.transactions t
    JOIN public.orders o ON t.order_id = o.id
    JOIN public.profiles p ON o.user_id = p.id
    ORDER BY t.created_at DESC;
END;
$$;

