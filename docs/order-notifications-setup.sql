-- Create custom types
CREATE TYPE public.order_status AS ENUM ('Pending', 'Processing', 'Shipped', 'Delivered', 'Cancelled');
CREATE TYPE public.notification_type AS ENUM ('new_order', 'new_review', 'new_question', 'new_user', 'refund_request', 'order_status_change');
CREATE TYPE public.user_role AS ENUM ('customer', 'manager', 'admin', 'super-admin');

-- Create tables
CREATE TABLE public.orders (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    order_number text UNIQUE NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    total_amount numeric(10, 2) NOT NULL,
    status public.order_status NOT NULL DEFAULT 'Pending',
    shipping_details jsonb NOT NULL,
    coupon_code text,
    discount_amount numeric(10, 2) DEFAULT 0,
    payment_method text
);
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.order_items (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id integer NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
    quantity integer NOT NULL,
    price_at_purchase numeric(10, 2) NOT NULL
);
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.transactions (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    amount numeric(10, 2) NOT NULL,
    payment_method text NOT NULL,
    status text NOT NULL DEFAULT 'Completed', -- e.g., Pending, Completed, Failed
    transaction_details jsonb,
    created_at timestamp with time zone NOT NULL DEFAULT now()
);
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.notifications (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE,
    recipient_role user_role, -- For role-based notifications e.g. to all admins
    title text NOT NULL,
    message text,
    link text, -- Link to the relevant page e.g. /admin/orders/123
    is_read boolean NOT NULL DEFAULT false,
    type notification_type,
    created_at timestamp with time zone NOT NULL DEFAULT now()
);
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;


-- Function to create an order
CREATE OR REPLACE FUNCTION public.create_order(
    p_user_id uuid,
    p_total_amount numeric,
    p_shipping_details jsonb,
    p_items jsonb,
    p_payment_method text,
    p_transaction_details jsonb,
    p_coupon_code text,
    p_discount_amount numeric
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER -- Use the permissions of the function owner
AS $$
DECLARE
    new_order_id bigint;
    new_order_number text;
    item record;
BEGIN
    -- Generate a unique order number
    new_order_number := 'ORD-' || to_char(now(), 'YYMMDD') || '-' || nextval('orders_id_seq');

    -- Insert into orders table
    INSERT INTO public.orders (user_id, order_number, total_amount, shipping_details, payment_method, coupon_code, discount_amount)
    VALUES (p_user_id, new_order_number, p_total_amount, p_shipping_details, p_payment_method, p_coupon_code, p_discount_amount)
    RETURNING id INTO new_order_id;

    -- Insert into order_items table
    FOR item IN SELECT * FROM jsonb_to_recordset(p_items) AS x(product_id int, quantity int, price numeric)
    LOOP
        INSERT INTO public.order_items (order_id, product_id, quantity, price_at_purchase)
        VALUES (new_order_id, item.product_id, item.quantity, item.price);
    END LOOP;
    
    -- Insert into transactions table
    INSERT INTO public.transactions (order_id, user_id, amount, payment_method, status, transaction_details)
    VALUES (new_order_id, p_user_id, p_total_amount, p_payment_method, 'Completed', p_transaction_details);

    -- Insert a notification for admins
    INSERT INTO public.notifications (recipient_role, title, message, link, type)
    VALUES ('admin', 'New Order Received', 'Order ' || new_order_number || ' has been placed.', '/admin/orders/' || new_order_number, 'new_order');

    RETURN new_order_number;
END;
$$;


-- Function to get admin order list
CREATE OR REPLACE FUNCTION public.get_admin_order_list()
RETURNS TABLE(
    id bigint,
    order_number text,
    created_at timestamp with time zone,
    total_amount numeric,
    status public.order_status,
    customer_name text,
    customer_email text,
    customer_avatar_url text
)
LANGUAGE sql STABLE SECURITY DEFINER
AS $$
    SELECT
        o.id,
        o.order_number,
        o.created_at,
        o.total_amount,
        o.status,
        COALESCE(p.full_name, (o.shipping_details->>'firstName') || ' ' || (o.shipping_details->>'lastName')) AS customer_name,
        COALESCE(u.email, o.shipping_details->>'email') AS customer_email,
        p.avatar_url AS customer_avatar_url
    FROM
        public.orders o
    LEFT JOIN
        public.profiles p ON o.user_id = p.id
    LEFT JOIN
        auth.users u ON o.user_id = u.id
    ORDER BY
        o.created_at DESC;
$$;

-- Function to get admin order details
CREATE OR REPLACE FUNCTION public.get_admin_order_details(p_order_number text)
RETURNS TABLE (
    id bigint,
    order_number text,
    created_at timestamp with time zone,
    total_amount numeric,
    status public.order_status,
    shipping_details jsonb,
    profiles jsonb,
    order_items jsonb,
    coupon_code text,
    discount_amount numeric,
    payment_method text,
    transaction_details jsonb
)
LANGUAGE sql STABLE SECURITY DEFINER
AS $$
    SELECT
        o.id,
        o.order_number,
        o.created_at,
        o.total_amount,
        o.status,
        o.shipping_details,
        jsonb_build_object('full_name', p.full_name, 'avatar_url', p.avatar_url) as profiles,
        (SELECT jsonb_agg(jsonb_build_object(
            'id', oi.id,
            'quantity', oi.quantity,
            'price_at_purchase', oi.price_at_purchase,
            'products', jsonb_build_object(
                'name', prod.name,
                'featured_image_url', prod.featured_image_url
            )
        )) FROM public.order_items oi JOIN public.products prod ON oi.product_id = prod.id WHERE oi.order_id = o.id) as order_items,
        o.coupon_code,
        o.discount_amount,
        t.payment_method,
        t.transaction_details
    FROM public.orders o
    LEFT JOIN public.profiles p ON o.user_id = p.id
    LEFT JOIN public.transactions t ON o.id = t.order_id
    WHERE o.order_number = p_order_number;
$$;

-- Function to get admin notifications
CREATE OR REPLACE FUNCTION public.get_admin_notifications()
RETURNS TABLE (
    id bigint,
    title text,
    message text,
    link text,
    is_read boolean,
    created_at timestamp with time zone,
    type notification_type
)
LANGUAGE sql STABLE SECURITY DEFINER
AS $$
    SELECT id, title, message, link, is_read, created_at, type
    FROM public.notifications
    WHERE recipient_role = 'admin' OR recipient_role = 'super-admin'
    ORDER BY created_at DESC
    LIMIT 20;
$$;

