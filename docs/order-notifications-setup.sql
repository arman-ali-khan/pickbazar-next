-- Drop old versions of the function to ensure a clean slate
DROP FUNCTION IF EXISTS public.create_order(uuid, numeric, jsonb, jsonb, text, jsonb);
DROP FUNCTION IF EXISTS public.create_order(uuid, numeric, jsonb, jsonb, text, jsonb, text, numeric);

-- Recreate the notification type enum correctly
DROP TYPE IF EXISTS public.notification_type;
CREATE TYPE public.notification_type AS ENUM (
    'new_order',
    'new_review',
    'order_shipped',
    'order_placed'
);

-- Recreate the notifications table to ensure it's correct
DROP TABLE IF EXISTS public.notifications;
CREATE TABLE public.notifications (
    id bigint generated by default as identity primary key,
    user_id uuid references public.users,
    title text not null,
    message text,
    link text,
    is_read boolean default false,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    type public.notification_type
);

-- Give all users access to their own notifications and allow security-definer functions to insert
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Users can view their own notifications" ON public.notifications;
CREATE POLICY "Users can view their own notifications" ON public.notifications
    FOR SELECT USING (auth.uid() = user_id);
DROP POLICY IF EXISTS "Users can update their own notifications" ON public.notifications;
CREATE POLICY "Users can update their own notifications" ON public.notifications
    FOR UPDATE USING (auth.uid() = user_id);

-- This policy is crucial for the SECURITY DEFINER function to work
DROP POLICY IF EXISTS "Allow functions to insert notifications" ON public.notifications;
CREATE POLICY "Allow functions to insert notifications" ON public.notifications
    FOR INSERT WITH CHECK (true);
    
-- Allow defined functions to insert into transactions
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow functions to insert transactions" ON public.transactions;
CREATE POLICY "Allow functions to insert transactions" ON public.transactions
    FOR INSERT WITH CHECK (true);
    
-- Create the new, correct order creation function
CREATE OR REPLACE FUNCTION public.create_order(
    p_user_id uuid,
    p_total_amount numeric,
    p_shipping_details jsonb,
    p_items jsonb,
    p_payment_method text,
    p_transaction_details jsonb DEFAULT NULL,
    p_coupon_code text DEFAULT NULL,
    p_discount_amount numeric DEFAULT 0
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    new_order_id bigint;
    new_order_number text;
    item record;
    admin_users uuid[];
BEGIN
    -- 1. Create the order and get the ID
    INSERT INTO public.orders (user_id, total_amount, shipping_details, status, coupon_code, discount_amount)
    VALUES (p_user_id, p_total_amount, p_shipping_details, 'Pending', p_coupon_code, p_discount_amount)
    RETURNING id, order_number INTO new_order_id, new_order_number;

    -- 2. Insert order items
    FOR item IN SELECT * FROM jsonb_to_recordset(p_items) AS x(product_id int, quantity int, price numeric)
    LOOP
        INSERT INTO public.order_items (order_id, product_id, quantity, price_at_purchase)
        VALUES (new_order_id, item.product_id, item.quantity, item.price);
    END LOOP;

    -- 3. Create a transaction record
    INSERT INTO public.transactions (order_id, user_id, amount, payment_method, status, transaction_details)
    VALUES (new_order_id, p_user_id, p_total_amount, p_payment_method, 'Completed', p_transaction_details);

    -- 4. Create notifications for admins/managers
    SELECT array_agg(id) INTO admin_users FROM public.profiles WHERE role IN ('admin', 'manager', 'super-admin');

    IF array_length(admin_users, 1) > 0 THEN
      FOR i IN 1..array_length(admin_users, 1)
      LOOP
        INSERT INTO public.notifications (user_id, title, message, link, type)
        VALUES (admin_users[i], 'New Order Placed', 'A new order ' || new_order_number || ' has been placed.', '/admin/orders/' || new_order_number, 'new_order');
      END LOOP;
    END IF;

    -- 5. Create a notification for the customer
    INSERT INTO public.notifications (user_id, title, message, link, type)
    VALUES (p_user_id, 'Order Placed Successfully', 'Your order ' || new_order_number || ' has been received.', '/profile/my-orders/' || new_order_number, 'order_placed');

    -- 6. Return the order number
    RETURN new_order_number;
END;
$$;

