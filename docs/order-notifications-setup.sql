DROP POLICY IF EXISTS "Users can view their own order items" ON public.order_items;
DROP POLICY IF EXISTS "Users can view their own transactions" ON public.transactions;
DROP POLICY IF EXISTS "Users can view their own notifications" ON public.notifications;
DROP POLICY IF EXISTS "Users can manage their own refund requests" ON public.refunds;
DROP POLICY IF EXISTS "Admins can manage all refunds" ON public.refunds;

-- Recreate policies
CREATE POLICY "Users can view their own orders"
ON public.orders FOR SELECT
USING (auth.uid() = user_id);

CREATE POLICY "Users can view their own order items"
ON public.order_items FOR SELECT
USING (auth.uid() = (SELECT user_id FROM public.orders WHERE id = order_id));

CREATE POLICY "Users can view their own transactions"
ON public.transactions FOR SELECT
USING (auth.uid() = user_id);

CREATE POLICY "Users can view their own notifications"
ON public.notifications FOR SELECT
USING (auth.uid() = user_id);

CREATE POLICY "Users can manage their own refund requests"
ON public.refunds FOR ALL
USING (auth.uid() = user_id);

CREATE POLICY "Admins can manage all refunds"
ON public.refunds FOR ALL
USING (public.get_my_role() IN ('admin', 'manager', 'super-admin'));
