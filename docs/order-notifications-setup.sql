DROP SEQUENCE IF EXISTS public.order_number_seq;

-- == Step 1: Recreate Types ==
CREATE TYPE public.order_status AS ENUM ('Pending', 'Processing', 'Shipped', 'Delivered', 'Cancelled');
CREATE TYPE public.refund_status AS ENUM ('Pending', 'Approved', 'Rejected');
CREATE TYPE public.transaction_status AS ENUM ('Pending', 'Completed', 'Failed');
CREATE TYPE public.notification_type AS ENUM ('new_order', 'new_review', 'new_user', 'new_refund_request');

-- == Step 2: Recreate Sequence for Order Numbers ==
CREATE SEQUENCE public.order_number_seq START 1;

-- == Step 3: Recreate Tables ==

-- Orders Table
CREATE TABLE public.orders (
    id bigint generated by default as identity primary key,
    user_id uuid references public.profiles on delete set null,
    order_number text not null unique,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    status public.order_status default 'Pending'::public.order_status not null,
    total_amount numeric(10,2) not null,
    shipping_details jsonb,
    coupon_code text,
    discount_amount numeric(10,2)
);
alter table public.orders enable row level security;
create policy "Allow users to view their own orders" on public.orders for select using (auth.uid() = user_id);
create policy "Allow admins to access all orders" on public.orders for all using ((get_my_role() = ANY (ARRAY['admin'::text, 'manager'::text, 'super-admin'::text])));


-- Order Items Table
CREATE TABLE public.order_items (
    id bigint generated by default as identity primary key,
    order_id bigint references public.orders on delete cascade not null,
    product_id bigint references public.products on delete set null,
    quantity integer not null,
    price_at_purchase numeric(10,2) not null
);
alter table public.order_items enable row level security;
create policy "Allow users to view items in their own orders" on public.order_items for select using ((select auth.uid() from public.orders where id = order_id) = auth.uid());
create policy "Allow admins to access all order items" on public.order_items for all using ((get_my_role() = ANY (ARRAY['admin'::text, 'manager'::text, 'super-admin'::text])));


-- Transactions Table
CREATE TABLE public.transactions (
    id bigint generated by default as identity primary key,
    order_id bigint references public.orders on delete cascade not null,
    user_id uuid references public.profiles on delete set null,
    amount numeric(10,2) not null,
    payment_method text not null,
    status public.transaction_status not null,
    transaction_details jsonb,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);
alter table public.transactions enable row level security;
create policy "Allow users to view their own transactions" on public.transactions for select using (auth.uid() = user_id);
create policy "Allow admins to access all transactions" on public.transactions for all using ((get_my_role() = ANY (ARRAY['admin'::text, 'manager'::text, 'super-admin'::text])));


-- Notifications Table
CREATE TABLE public.notifications (
    id bigint generated by default as identity primary key,
    user_id uuid references public.profiles on delete set null,
    recipient_role user_role,
    type public.notification_type not null,
    title text not null,
    message text,
    link text,
    is_read boolean default false not null,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);
alter table public.notifications enable row level security;
create policy "Admins can view admin notifications" on public.notifications for select using ((get_my_role() = ANY (ARRAY['admin'::text, 'manager'::text, 'super-admin'::text])));
create policy "Users can view their own notifications" on public.notifications for select using ((auth.uid() = user_id));
create policy "Allow service roles to insert notifications" on public.notifications for insert with check (true);
create policy "Admins can update notifications" on public.notifications for update using ((get_my_role() = ANY (ARRAY['admin'::text, 'manager'::text, 'super-admin'::text])));


-- == Step 4: Recreate Functions with correct definitions ==

-- Function to create a new order and associated items
create or replace function public.create_order(
    p_user_id uuid,
    p_total_amount numeric,
    p_shipping_details jsonb,
    p_items jsonb,
    p_payment_method text,
    p_transaction_details jsonb,
    p_coupon_code text,
    p_discount_amount numeric
)
returns text as $$
declare
    new_order_id int;
    new_order_number text;
    item record;
    new_transaction_id int;
begin
    -- 1. Create a unique order number
    new_order_number := 'ORD-' || to_char(now(), 'YYMMDD') || '-' || nextval('order_number_seq');

    -- 2. Insert into orders table (FIXED: Added order_number)
    insert into public.orders (user_id, order_number, total_amount, shipping_details, coupon_code, discount_amount)
    values (p_user_id, new_order_number, p_total_amount, p_shipping_details, p_coupon_code, p_discount_amount)
    returning id into new_order_id;

    -- 3. Insert into order_items table
    for item in select * from jsonb_to_recordset(p_items) as x(product_id int, quantity int, price numeric)
    loop
        insert into public.order_items (order_id, product_id, quantity, price_at_purchase)
        values (new_order_id, item.product_id, item.quantity, item.price);
    end loop;

    -- 4. Insert into transactions table
    insert into public.transactions (order_id, user_id, amount, payment_method, transaction_details, status)
    values (new_order_id, p_user_id, p_total_amount, p_payment_method, p_transaction_details, 'Completed')
    returning id into new_transaction_id;

    -- 5. Insert notification for admin
    insert into public.notifications (user_id, recipient_role, type, title, message, link)
    values (p_user_id, 'admin', 'new_order', 'New Order Received', 'A new order ' || new_order_number || ' has been placed.', '/admin/orders/' || new_order_number);

    -- 6. Return the new order number
    return new_order_number;
end;
$$ language plpgsql volatile security definer;


-- get_admin_order_list
create or replace function public.get_admin_order_list()
returns table(
    id bigint,
    order_number text,
    created_at timestamp with time zone,
    total_amount numeric,
    status public.order_status,
    customer_name text,
    customer_email text,
    customer_avatar_url text
) as $$
begin
    return query
    select
        o.id,
        o.order_number,
        o.created_at,
        o.total_amount,
        o.status,
        p.full_name as customer_name,
        u.email as customer_email,
        p.avatar_url as customer_avatar_url
    from
        public.orders o
        left join public.profiles p on o.user_id = p.id
        left join auth.users u on o.user_id = u.id
    order by
        o.created_at desc;
end;
$$ language plpgsql stable security definer;

-- get_admin_order_details
create or replace function public.get_admin_order_details(p_order_number text)
returns table (
    id bigint,
    order_number text,
    created_at timestamp with time zone,
    total_amount numeric,
    status public.order_status,
    shipping_details jsonb,
    profiles jsonb,
    order_items jsonb,
    coupon_code text,
    discount_amount numeric,
    payment_method text,
    transaction_details jsonb
) as $$
begin
    return query
    select
        o.id,
        o.order_number,
        o.created_at,
        o.total_amount,
        o.status,
        o.shipping_details,
        jsonb_build_object('full_name', p.full_name, 'avatar_url', p.avatar_url) as profiles,
        (select jsonb_agg(jsonb_build_object(
            'id', oi.id,
            'quantity', oi.quantity,
            'price_at_purchase', oi.price_at_purchase,
            'products', jsonb_build_object(
                'name', prod.name,
                'featured_image_url', prod.featured_image_url
            )
        )) from public.order_items oi join public.products prod on oi.product_id = prod.id where oi.order_id = o.id) as order_items,
        o.coupon_code,
        o.discount_amount,
        t.payment_method,
        t.transaction_details
    from public.orders o
    left join public.profiles p on o.user_id = p.id
    left join public.transactions t on o.id = t.order_id
    where o.order_number = p_order_number;
end;
$$ language plpgsql stable security definer;


-- get_admin_notifications
create or replace function public.get_admin_notifications()
returns table (
    id bigint,
    title text,
    message text,
    link text,
    is_read boolean,
    created_at timestamp with time zone,
    type public.notification_type
) as $$
begin
    return query
    select
        n.id,
        n.title,
        n.message,
        n.link,
        n.is_read,
        n.created_at,
        n.type
    from public.notifications n
    where n.recipient_role = 'admin'
    order by n.created_at desc;
end;
$$ language plpgsql stable security definer;


-- get_admin_transactions
create or replace function public.get_admin_transactions()
returns table (
    id bigint,
    order_id bigint,
    order_number text,
    customer_name text,
    customer_avatar text,
    amount numeric,
    payment_method text,
    status public.transaction_status,
    created_at timestamp with time zone
) as $$
begin
    return query
    select
        t.id,
        t.order_id,
        o.order_number,
        p.full_name as customer_name,
        p.avatar_url as customer_avatar,
        t.amount,
        t.payment_method,
        t.status,
        t.created_at
    from public.transactions t
    join public.orders o on t.order_id = o.id
    left join public.profiles p on t.user_id = p.id
    order by t.created_at desc;
end;
$$ language plpgsql stable security definer;


