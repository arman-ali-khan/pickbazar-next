CREATE OR REPLACE FUNCTION public.get_admin_notifications()
RETURNS TABLE (
  id bigint,
  title text,
  message text,
  link text,
  is_read boolean,
  created_at timestamp with time zone,
  type text
) AS $$
BEGIN
  IF is_admin(auth.uid()) THEN
    RETURN QUERY
    SELECT
      n.id,
      n.title,
      n.message,
      n.link,
      n.is_read,
      n.created_at,
      n.type
    FROM
      public.notifications n
    ORDER BY
      n.created_at DESC
    LIMIT 50;
  END IF;
END;
$$ LANGUAGE plpgsql;

-- Add back other RPC functions that might have been dropped
-- It is safer to recreate them.
CREATE OR REPLACE FUNCTION public.get_my_role()
RETURNS TABLE(role text) AS $$
BEGIN
  RETURN QUERY
  SELECT p.role FROM public.profiles p WHERE p.id = auth.uid();
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION public.get_admin_orders()
RETURNS TABLE (
    id bigint,
    order_number text,
    created_at timestamp with time zone,
    total_amount numeric,
    status public.order_status,
    customer_name text,
    customer_email text,
    customer_avatar_url text
) AS $$
BEGIN
    RETURN QUERY
    SELECT
        o.id,
        o.order_number,
        o.created_at,
        o.total_amount,
        o.status,
        COALESCE(p.full_name, (o.shipping_details ->> 'firstName') || ' ' || (o.shipping_details ->> 'lastName')) AS customer_name,
        COALESCE(u.email, o.shipping_details ->> 'email') as customer_email,
        p.avatar_url AS customer_avatar_url
    FROM
        public.orders o
    LEFT JOIN
        public.profiles p ON o.user_id = p.id
    LEFT JOIN
        auth.users u ON o.user_id = u.id
    ORDER BY
        o.created_at DESC;
END;
$$ LANGUAGE plpgsql;

