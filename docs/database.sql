-- Combined function to create an order and its items.
DROP FUNCTION IF EXISTS public.create_order(double precision, jsonb, jsonb, text, jsonb, double precision, text, text);
CREATE OR REPLACE FUNCTION public.create_order(
    p_total_amount double precision,
    p_shipping_details jsonb,
    p_items jsonb,
    p_payment_method text,
    p_transaction_details jsonb,
    p_discount_amount double precision,
    p_coupon_code text,
    p_initial_status text
)
RETURNS text
LANGUAGE plpgsql
AS $$
DECLARE
    v_order_id bigint;
    v_order_number text;
    item jsonb;
BEGIN
    -- Generate a unique order number
    v_order_number := 'KB-' || to_char(now(), 'YYYYMMDD') || '-' || (
        SELECT lpad( (count(*) + 1)::text, 4, '0')
        FROM orders
        WHERE created_at >= date_trunc('day', now())
    );

    -- Insert into orders table
    INSERT INTO public.orders (
        user_id, total_amount, status, shipping_details, order_number,
        payment_method, payment_details, discount_amount, coupon_code
    )
    VALUES (
        auth.uid(), p_total_amount, p_initial_status, p_shipping_details, v_order_number,
        p_payment_method, p_transaction_details, p_discount_amount, p_coupon_code
    ) RETURNING id INTO v_order_id;

    -- Loop through items and insert into order_items
    FOR item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        INSERT INTO public.order_items (order_id, product_id, quantity, price_at_purchase)
        VALUES (v_order_id, (item->>'product_id')::bigint, (item->>'quantity')::int, (item->>'price')::double precision);

        -- Decrement stock
        UPDATE public.products
        SET stock = stock - (item->>'quantity')::int
        WHERE id = (item->>'product_id')::bigint;
    END LOOP;

    RETURN v_order_number;
END;
$$;


