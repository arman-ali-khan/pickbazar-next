-- Replace the create_order function
CREATE OR REPLACE FUNCTION public.create_order(p_total_amount numeric, p_shipping_details jsonb, p_items jsonb, p_payment_method text, p_transaction_details jsonb, p_coupon_code text, p_discount_amount numeric, p_initial_status public.order_status)
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
  new_order_id bigint;
  new_order_number text;
  item jsonb;
  new_transaction_id bigint;
  current_user_id uuid := auth.uid();
BEGIN
  -- Insert the order and get the new ID and order_number
  INSERT INTO public.orders (user_id, total_amount, shipping_details, coupon_code, discount_amount, payment_method, status)
  VALUES (current_user_id, p_total_amount, p_shipping_details, p_coupon_code, p_discount_amount, p_payment_method, p_initial_status)
  RETURNING id, order_number INTO new_order_id, new_order_number;

  -- Insert order items
  FOR item IN SELECT * FROM jsonb_array_elements(p_items)
  LOOP
    INSERT INTO public.order_items (order_id, product_id, quantity, price_at_purchase)
    VALUES (new_order_id, (item->>'id')::bigint, (item->>'quantity')::int, (item->>'price')::numeric);
    
    -- Decrement stock
    UPDATE public.products
    SET stock = stock - (item->>'quantity')::int
    WHERE id = (item->>'id')::bigint;
  END LOOP;

  -- Insert transaction record
  INSERT INTO public.transactions(user_id, order_id, amount, payment_method, status, transaction_details)
  VALUES (current_user_id, new_order_id, p_total_amount, p_payment_method, 'Completed', p_transaction_details)
  RETURNING id INTO new_transaction_id;
  
  -- Return the order_number
  RETURN new_order_number;
END;
$function$;

-- Function to log order status changes
CREATE OR REPLACE FUNCTION public.log_order_status_change()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.order_history(order_id, status)
    VALUES(NEW.id, NEW.status);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Trigger for order status changes
DROP TRIGGER IF EXISTS on_order_status_change ON public.orders;
CREATE TRIGGER on_order_status_change
AFTER INSERT OR UPDATE OF status ON public.orders
FOR EACH ROW
EXECUTE FUNCTION public.log_order_status_change();


