-- Drop the old, incorrect version of the function first to resolve ambiguity.
-- This version accepts 'text' for p_initial_status.
DROP FUNCTION IF EXISTS public.create_order(numeric, jsonb, jsonb, text, jsonb, text, numeric, text);


-- Function to create an order and related items
CREATE OR REPLACE FUNCTION public.create_order(
    p_total_amount numeric,
    p_shipping_details jsonb,
    p_items jsonb,
    p_payment_method text,
    p_transaction_details jsonb,
    p_coupon_code text,
    p_discount_amount numeric,
    p_initial_status public.order_status DEFAULT 'Pending'
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  new_order_id bigint;
  new_order_number text;
  item jsonb;
  current_user_id uuid;
BEGIN
  -- Get the current user's ID from the auth context
  current_user_id := auth.uid();
  
  -- Generate a unique order number
  new_order_number := 'KB-' || to_char(now(), 'YYYYMMDD') || '-' || substr(md5(random()::text), 1, 6);

  -- Insert the new order
  INSERT INTO public.orders (
    user_id,
    total_amount,
    shipping_details,
    status,
    order_number,
    coupon_code,
    discount_amount
  )
  VALUES (
    current_user_id,
    p_total_amount,
    p_shipping_details,
    p_initial_status,
    new_order_number,
    p_coupon_code,
    p_discount_amount
  )
  RETURNING id INTO new_order_id;

  -- Insert order items
  FOR item IN SELECT * FROM jsonb_array_elements(p_items)
  LOOP
    INSERT INTO public.order_items (order_id, product_id, quantity, price_at_purchase)
    VALUES (
      new_order_id,
      (item->>'product_id')::bigint,
      (item->>'quantity')::integer,
      (item->>'price')::numeric
    );
  END LOOP;
  
  -- Insert a corresponding transaction record
  INSERT INTO public.transactions (order_id, user_id, amount, payment_method, transaction_details, status)
  VALUES (
      new_order_id,
      current_user_id,
      p_total_amount,
      p_payment_method,
      p_transaction_details,
      CASE 
          WHEN p_initial_status = 'Processing' THEN 'Completed'::text
          ELSE 'Pending'::text
      END
  );

  RETURN new_order_number;
END;
$$;