CREATE OR REPLACE FUNCTION public.get_category_tree()
RETURNS TABLE (
    name text,
    subcategories text[]
) AS $$
BEGIN
    RETURN QUERY
    SELECT
        p.name,
        ARRAY_AGG(c.name)
    FROM public.categories p
    LEFT JOIN public.categories c ON c.parent_id = p.id
    WHERE p.parent_id IS NULL
    GROUP BY p.id, p.name
    ORDER BY p.name;
END;
