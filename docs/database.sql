    RETURN QUERY
    SELECT
        COUNT(*) as total_reviews,
        COALESCE(AVG(rating), 0) as avg_rating,
        jsonb_agg(
            jsonb_build_object('rating', rating, 'count', count)
        ) as rating_distribution
    FROM (
        SELECT
            rating,
            COUNT(*) as count
        FROM reviews
        WHERE product_id = p_product_id AND status = 'Approved'
        GROUP BY rating
    ) as rating_counts;
END;
$$;


