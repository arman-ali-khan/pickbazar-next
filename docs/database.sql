-- Function to get related products (More resilient version)
DROP FUNCTION IF EXISTS get_related_products(integer, integer);
CREATE OR REPLACE FUNCTION get_related_products(p_id integer, p_limit integer)
RETURNS SETOF products AS $$
BEGIN
    RETURN QUERY
    WITH product_details AS (
        SELECT
            (SELECT array_agg(category_id) FROM product_categories WHERE product_id = p_id) as cats,
            (SELECT array_agg(tag_id) FROM product_tags WHERE product_id = p_id) as tags,
            (SELECT category_id FROM product_categories WHERE product_id = p_id LIMIT 1) as main_cat
    ),
    scored_products AS (
        SELECT
            p.id,
            (
                (SELECT COUNT(*) FROM product_categories pc WHERE pc.product_id = p.id AND pc.category_id = ANY((SELECT cats FROM product_details))) * 2
            ) +
            (
                (SELECT COUNT(*) FROM product_tags pt WHERE pt.product_id = p.id AND pt.tag_id = ANY((SELECT tags FROM product_details)))
            ) as relevance_score
        FROM products p
        WHERE p.id != p_id AND p.status = 'active'
    )
    (
        SELECT p.*
        FROM products p
        JOIN scored_products s ON p.id = s.id
        WHERE s.relevance_score > 0
        ORDER BY s.relevance_score DESC, p.view_count DESC NULLS LAST
        LIMIT p_limit
    )
    UNION
    (
        SELECT p.*
        FROM products p
        JOIN product_categories pc on p.id = pc.product_id
        WHERE p.id != p_id
            AND p.status = 'active'
            AND pc.category_id = (SELECT main_cat FROM product_details)
            AND p.id NOT IN (SELECT id FROM products p JOIN scored_products s ON p.id = s.id WHERE s.relevance_score > 0)
        ORDER BY p.view_count DESC NULLS LAST
        LIMIT p_limit
    )
    LIMIT p_limit;
END;
$$ LANGUAGE plpgsql;


-- Function to get recommended products (More resilient version)
DROP FUNCTION IF EXISTS get_recommended_products(integer);
CREATE OR REPLACE FUNCTION public.get_recommended_products(p_limit integer)
RETURNS SETOF products
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RETURN QUERY
    WITH product_scores AS (
        SELECT
            p.id,
            COALESCE((SELECT COUNT(*) FROM order_items oi WHERE oi.product_id = p.id), 0) as sales_count,
            COALESCE((SELECT COUNT(*) FROM wishlist w WHERE w.product_id = p.id), 0) as wishlist_count,
            COALESCE(p.view_count, 0) as view_count,
            p.created_at
        FROM
            products p
        WHERE p.status = 'active'
    ),
    ranked_products AS (
        SELECT
            ps.id,
            -- Weighted score: Sales (50%), Wishlists (30%), Views (20%)
            (ps.sales_count * 0.5) + (ps.wishlist_count * 0.3) + (ps.view_count * 0.2) as score,
            ps.created_at
        FROM
            product_scores ps
    )
    (
        SELECT p.*
        FROM products p
        JOIN ranked_products rp ON p.id = rp.id
        WHERE rp.score > 0
        ORDER BY rp.score DESC, p.created_at DESC
        LIMIT p_limit
    )
    UNION
    (
        SELECT p.*
        FROM products p
        WHERE p.status = 'active'
        AND p.id NOT IN (SELECT id FROM ranked_products WHERE score > 0)
        ORDER BY p.created_at DESC
        LIMIT p_limit
    )
    LIMIT p_limit;
END;
$$;


