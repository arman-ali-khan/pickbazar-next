-- Function to log order status changes to the history table
DROP FUNCTION IF EXISTS public.log_order_status_change();
create function public.log_order_status_change()
returns trigger
language plpgsql
as $$
begin
    -- On insert, log the initial status
    if TG_OP = 'INSERT' then
        insert into order_history (order_id, status)
        values (new.id, new.status);
    -- On update, only log if the status has actually changed
    elsif TG_OP = 'UPDATE' and new.status is distinct from old.status then
        insert into order_history (order_id, status)
        values (new.id, new.status);
    end if;
    return new;
end;
$$;

-- Trigger to log order status change
drop trigger if exists on_order_status_change on public.orders;
create trigger on_order_status_change
after insert or update of status on orders
for each row
execute procedure log_order_status_change();


