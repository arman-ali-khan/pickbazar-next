CREATE OR REPLACE FUNCTION public.log_order_status_change()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.order_history (order_id, status)
    VALUES (NEW.id, NEW.status);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS order_status_trigger ON public.orders;
CREATE TRIGGER order_status_trigger
AFTER INSERT OR UPDATE OF status ON public.orders
FOR EACH ROW
EXECUTE FUNCTION public.log_order_status_change();


-- Create RPC Function for creating orders
CREATE OR REPLACE FUNCTION public.create_order(
    p_total_amount numeric,
    p_shipping_details jsonb,
    p_items jsonb,
    p_payment_method text,
    p_transaction_details jsonb,
    p_coupon_code text,
    p_discount_amount numeric,
    p_initial_status public.order_status
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    new_order_id bigint;
    new_order_number text;
    item jsonb;
    current_product_stock int;
    order_seq_val bigint;
BEGIN
    -- Generate a unique order number
    SELECT nextval('orders_id_seq') INTO order_seq_val;
    new_order_number := 'KB-' || to_char(now(), 'YYMMDD') || '-' || order_seq_val;
    
    -- Insert the order
    INSERT INTO public.orders (
        id, user_id, order_number, total_amount, shipping_details, 
        payment_method, coupon_code, discount_amount, status
    )
    VALUES (
        order_seq_val, auth.uid(), new_order_number, p_total_amount, p_shipping_details, 
        p_payment_method, p_coupon_code, p_discount_amount, p_initial_status
    )
    RETURNING id INTO new_order_id;
    
    -- Insert order items and update stock
    FOR item IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        -- Check current stock
        SELECT stock INTO current_product_stock FROM public.products WHERE id = (item->>'product_id')::bigint;

        IF current_product_stock IS NULL OR current_product_stock < (item->>'quantity')::int THEN
            RAISE EXCEPTION 'Insufficient stock for product ID %', (item->>'product_id')::bigint;
        END IF;

        -- Insert order item
        INSERT INTO public.order_items (order_id, product_id, quantity, price_at_purchase)
        VALUES (new_order_id, (item->>'product_id')::bigint, (item->>'quantity')::int, (item->>'price')::numeric);
        
        -- Update product stock
        UPDATE public.products 
        SET stock = stock - (item->>'quantity')::int 
        WHERE id = (item->>'product_id')::bigint;
    END LOOP;

    -- Insert transaction details
    IF p_transaction_details IS NOT NULL OR p_payment_method = 'cod' THEN
      -- Create a placeholder transactions table if it doesn't exist, to avoid errors
      CREATE TABLE IF NOT EXISTS public.transactions (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          order_id bigint NOT NULL REFERENCES public.orders(id),
          user_id uuid NOT NULL REFERENCES auth.users(id),
          amount numeric NOT NULL,
          payment_method text,
          status text,
          transaction_details jsonb,
          created_at timestamp with time zone DEFAULT now()
      );
      INSERT INTO public.transactions (order_id, user_id, amount, payment_method, status, transaction_details)
      VALUES (new_order_id, auth.uid(), p_total_amount, p_payment_method, 'Completed', p_transaction_details);
    END IF;

    RETURN new_order_number;
END;
$$;


CREATE OR REPLACE FUNCTION public.update_order_status_and_log(p_order_id bigint, p_new_status text)
RETURNS SETOF public.orders
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE public.orders
    SET status = p_new_status::public.order_status
    WHERE id = p_order_id;
    
    RETURN QUERY SELECT * FROM public.orders WHERE id = p_order_id;
END;
$$;

