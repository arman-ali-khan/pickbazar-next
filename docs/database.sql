RETURNS TABLE (name text, subcategories text[])
LANGUAGE sql
AS $$
    with parent_cats as (
        select id, name from categories where parent_id is null
    )
    select
        pc.name,
        array_agg(c.name) as subcategories
    from parent_cats pc
    join categories c on c.parent_id = pc.id
    group by pc.name;
