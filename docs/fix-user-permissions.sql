-- =================================================================
-- MASTER DATABASE SETUP SCRIPT FOR PICKBAZAR
-- This script sets up tables, functions, and security policies.
-- Run this script in your Supabase SQL Editor.
-- =================================================================

-- Drop existing objects in reverse order of dependency to avoid errors.
-- Policies depend on functions, so drop policies first.
DROP POLICY IF EXISTS "Allow admin select for contact messages" ON public.contact_messages;
DROP POLICY IF EXISTS "Allow admin update for contact messages" ON public.contact_messages;
DROP POLICY IF EXISTS "Allow admin delete for contact messages" ON public.contact_messages;
DROP POLICY IF EXISTS "Allow public insert for contact messages" ON public.contact_messages;

DROP POLICY IF EXISTS "Allow admin full access for settings" ON public.settings;

-- Now, functions can be dropped.
DROP FUNCTION IF EXISTS is_admin(user_id uuid);
DROP FUNCTION IF EXISTS get_all_users();
DROP FUNCTION IF EXISTS get_admin_reviews();
DROP FUNCTION IF EXISTS get_admin_refunds();
DROP FUNCTION IF EXISTS get_contact_messages();
DROP FUNCTION IF EXISTS get_contact_message_details(p_message_id BIGINT);
DROP FUNCTION IF EXISTS get_all_settings();

-- =================================================================
-- TABLES
-- =================================================================

-- Create settings table
CREATE TABLE IF NOT EXISTS public.settings (
    key TEXT PRIMARY KEY,
    value TEXT
);

-- Create contact_messages table
CREATE TABLE IF NOT EXISTS public.contact_messages (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    subject TEXT NOT NULL,
    message TEXT NOT NULL,
    status TEXT DEFAULT 'unread' NOT NULL, -- e.g., 'unread', 'read', 'archived'
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- =================================================================
-- HELPER FUNCTIONS & SECURITY
-- =================================================================

-- Create the is_admin function with SECURITY DEFINER
CREATE OR REPLACE FUNCTION is_admin(user_id uuid)
RETURNS boolean AS $$
DECLARE
  user_role TEXT;
BEGIN
  -- Use SECURITY DEFINER to securely access the profiles table
  -- even within other RLS policies.
  SELECT role::text INTO user_role FROM public.profiles WHERE id = user_id;
  RETURN user_role IN ('admin', 'manager', 'super-admin');
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


-- =================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- =================================================================

-- Enable RLS for settings table
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;
-- Policy for settings: Allow admins full access.
CREATE POLICY "Allow admin full access for settings" ON public.settings
    FOR ALL
    USING (is_admin(auth.uid()))
    WITH CHECK (is_admin(auth.uid()));

-- Enable RLS for contact_messages table
ALTER TABLE public.contact_messages ENABLE ROW LEVEL SECURITY;
-- Policy for contact_messages: Allow public insert.
CREATE POLICY "Allow public insert for contact messages" ON public.contact_messages
    FOR INSERT WITH CHECK (true);
-- Policy for contact_messages: Allow admins to select/view.
CREATE POLICY "Allow admin select for contact messages" ON public.contact_messages
    FOR SELECT USING (is_admin(auth.uid()));
-- Policy for contact_messages: Allow admins to update.
CREATE POLICY "Allow admin update for contact messages" ON public.contact_messages
    FOR UPDATE USING (is_admin(auth.uid()));
-- Policy for contact_messages: Allow admins to delete.
CREATE POLICY "Allow admin delete for contact messages" ON public.contact_messages
    FOR DELETE USING (is_admin(auth.uid()));


