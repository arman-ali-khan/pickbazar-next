-- Function to get all users for the admin user management page.
CREATE OR REPLACE FUNCTION get_all_users()
RETURNS TABLE (
    id UUID,
    full_name TEXT,
    email TEXT,
    avatar_url TEXT,
    created_at TIMESTAMPTZ,
    role TEXT
)
LANGUAGE sql
SECURITY DEFINER
AS $$
    SELECT
        p.id,
        p.full_name,
        u.email,
        p.avatar_url,
        u.created_at,
        p.role::text
    FROM public.profiles p
    JOIN auth.users u ON p.id = u.id
    ORDER BY u.created_at DESC;
$$;


-- Function to get reviews for the admin reviews page.
CREATE OR REPLACE FUNCTION get_admin_reviews()
RETURNS TABLE (
    id BIGINT,
    rating INT,
    text TEXT,
    status TEXT,
    created_at TIMESTAMPTZ,
    author JSONB,
    product JSONB
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RETURN QUERY
    SELECT
        r.id,
        r.rating,
        r.text,
        r.status::text,
        r.created_at,
        json_build_object(
            'name', p.full_name,
            'avatar_url', p.avatar_url
        ) AS author,
        json_build_object(
            'id', pr.id,
            'name', pr.name,
            'featured_image_url', pr.featured_image_url
        ) AS product
    FROM public.reviews r
    JOIN public.profiles p ON r.user_id = p.id
    JOIN public.products pr ON r.product_id = pr.id
    ORDER BY r.created_at DESC;
END;
$$;

-- Function to get refund requests for the admin refunds page.
CREATE OR REPLACE FUNCTION get_admin_refunds()
RETURNS TABLE(
    id bigint,
    order_id bigint,
    order_number text,
    amount real,
    status text,
    reason text,
    created_at timestamptz,
    user_id uuid,
    customer_name text,
    customer_avatar_url text
)
LANGUAGE plpgsql
AS $$
BEGIN
  RETURN QUERY
  SELECT
    r.id,
    r.order_id,
    o.order_number,
    r.amount,
    r.status::text,
    r.reason,
    r.created_at,
    r.user_id,
    p.full_name as customer_name,
    p.avatar_url as customer_avatar_url
  FROM refunds r
  JOIN profiles p ON r.user_id = p.id
  JOIN orders o ON r.order_id = o.id
  ORDER BY r.created_at DESC;
END;
$$;

-- Function to securely get all contact messages for the admin page.
CREATE OR REPLACE FUNCTION get_contact_messages()
RETURNS TABLE (
    id BIGINT,
    senderName TEXT,
    senderEmail TEXT,
    subject TEXT,
    message TEXT,
    status TEXT,
    date TIMESTAMPTZ
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    IF NOT is_admin(auth.uid()) THEN
        RAISE EXCEPTION 'Permission denied.';
    END IF;

    RETURN QUERY
    SELECT
        cm.id,
        cm.name as senderName,
        cm.email as senderEmail,
        cm.subject,
        cm.message,
        cm.status,
        cm.created_at as date
    FROM public.contact_messages cm
    ORDER BY cm.created_at DESC;
END;
$$;

-- Function to get a single contact message's details.
CREATE OR REPLACE FUNCTION get_contact_message_details(p_message_id BIGINT)
RETURNS TABLE (
    id BIGINT,
    senderName TEXT,
    senderEmail TEXT,
    subject TEXT,
    message TEXT,
    status TEXT,
    date TIMESTAMPTZ,
    avatar JSONB
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    IF NOT is_admin(auth.uid()) THEN
        RAISE EXCEPTION 'Permission denied.';
    END IF;

    RETURN QUERY
    SELECT
        cm.id,
        cm.name as senderName,
        cm.email as senderEmail,
        cm.subject,
        cm.message,
        cm.status,
        cm.created_at as date,
        jsonb_build_object(
            'imageUrl', NULL,
            'imageHint', 'person icon'
        ) as avatar
    FROM public.contact_messages cm
    WHERE cm.id = p_message_id;
END;
$$;

-- Function to get all settings as a single JSON object.
CREATE OR REPLACE FUNCTION get_all_settings()
RETURNS json AS $$
DECLARE
    settings_json json;
BEGIN
    SELECT json_object_agg(key, value)
    INTO settings_json
    FROM public.settings;
    RETURN settings_json;
END;
$$ LANGUAGE plpgsql;